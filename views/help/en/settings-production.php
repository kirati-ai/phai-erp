<?php /** How to use the Production settings page (opened from the Help button, top right) */ ?>
<h3>What this page is for</h3>
<p>Sets the document numbers of production work: work orders (WO) and quality checks (QC) — the prefix, the format and the next number</p>

<h3>Where it sits in the system</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">Comes from</td><td>The starting values from the installation</td></tr>
    <tr><td class="text-nowrap">Goes to</td><td>The numbers of work orders and quality check results when you click save</td></tr>
    <tr><td class="text-nowrap">Document name</td><td>Document numbering — internal documents</td></tr>
    <tr><td class="text-nowrap">Posting</td><td>No posting</td></tr>
</table>

<h3>Change the document numbers</h3>
<ol>
    <li>Change the prefix, format or next number and see the result in the <b>Example</b> column</li>
    <li>Click <b>Save</b> — it applies to new documents only</li>
</ol>
<p class="text-secondary">All modules are together in System settings → <b>Document numbering</b></p>