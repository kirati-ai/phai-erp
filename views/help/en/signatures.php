<?php /** How to use the Documents to sign page (opened from the Help button, top right) */ ?>
<h3>What this page is</h3>
<p>The documents someone <b>asked you to sign</b>, and the ones <b>you asked others to sign</b> — click a document to open its page, then sign or reject in that signature box</p>

<h3>Where it sits in the system</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">Comes from</td><td>The <b>Signatures</b> button beside every document's print button → under a signature box, <b>Ask to sign</b> and pick the signer (only people allowed to open that document)</td></tr>
    <tr><td class="text-nowrap">Goes to</td><td>Once signed, the signature, name and date show in that box of the printed page and the PDF at once, with the company stamp (when set)</td></tr>
    <tr><td class="text-nowrap">Document name</td><td>Electronic signature on a document; who signed, when and from which machine is kept</td></tr>
    <tr><td class="text-nowrap">Posting</td><td>No posting</td></tr>
</table>

<h3>Set your signature</h3>
<ol>
    <li>Click your name, top right → <b>My signature</b></li>
    <li>Sign in the box with a mouse or a finger, or <b>Upload picture</b> (a photo of a signature on white paper works: it is trimmed and made transparent)</li>
    <li>Click <b>Use this signature</b> — it is kept as a PNG of at most 600 × 200 pixels and prints at most 4 cm wide</li>
</ol>

<h3>Kinds of signature box</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">Ours</td><td>e.g. prepared by, sent by, received by — anyone allowed to print the document can <b>Sign</b> it themselves (the name shown is the signer's)</td></tr>
    <tr><td class="text-nowrap">Approval</td><td>e.g. approved by, checked by, authorized signature — only the person asked to sign, or an ADMIN</td></tr>
    <tr><td class="text-nowrap">Customer / vendor</td><td>e.g. received by, paid by — left blank to be signed on paper</td></tr>
</table>

<h3>Good to know</h3>
<ul>
    <li>With e-mail set up (the e-Tax settings page) a request also e-mails the signer a link — opening it always asks to log in first. Without e-mail the request still shows here and on the <b>Waiting for me</b> button in the top bar</li>
    <li>Change a document after it is signed (amounts, lines, customer) and the signature no longer prints; the box says "sign again"</li>
    <li>Changing your signature later does not touch documents already signed</li>
    <li>The company stamp is set on the <b>Company</b> page and prints only on signed documents sent to a customer or vendor</li>
</ul>
