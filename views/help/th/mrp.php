<h3>หน้านี้ใช้ทำอะไร</h3>
<p>วางแผนว่าต้อง <b>ซื้อ</b> หรือ <b>ผลิต</b> อะไร เท่าไร เมื่อไร ให้พอส่งตามใบสั่งขายและพอเบิกเข้าใบสั่งผลิต — ทำแบบเดียวกับระบบ ERP ใหญ่ (QAD, SAP): ผู้วางแผนกด <b>รัน MRP</b> ระบบไล่สินค้าทีละระดับของสูตรการผลิต ได้ <b>ใบสั่งตามแผน</b> และ <b>ข้อความแนะนำ</b> แล้วผู้วางแผนตัดสินใจทำตาม</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td><b>ใบสั่งขาย</b> ค้างส่ง <b>ใบสั่งผลิต</b> ค้างเบิก สต็อก <b>ใบขอซื้อ</b> <b>ใบสั่งซื้อ</b> ค้างรับ <b>สูตรการผลิต</b> ข้อมูลการวางแผนของ <b>สินค้าและวัตถุดิบ</b> (ระยะเวลาสั่ง ขนาดสั่ง) และ <b>วางแผนสินค้าแยกสาขา</b> (สต็อกสำรอง)</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>ใบสั่งตามแผนประเภทซื้อ → <b>ใบขอซื้อ</b> → ใบสั่งซื้อ → รับสินค้า; ประเภทผลิต → <b>ใบสั่งผลิต</b> (วัตถุดิบในใบสั่งผลิตคือที่ MRP กระจายจากสูตรเดียวกัน)</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>การวางแผนความต้องการวัสดุ (Material Requirements Planning, MRP) — ผลเป็นใบสั่งตามแผน (Planned Order) ไม่ใช่เอกสาร</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี</td></tr>
</table>

<h3>รัน MRP ทำอะไร</h3>
<ol>
    <li>เริ่มจากสินค้าระดับบนสุด (ระดับ 0 = สินค้าที่ขาย) ลงไปทีละระดับตามสูตรการผลิต (Low-level code)</li>
    <li>แต่ละสินค้า: <b>ความต้องการรวม</b> = ใบสั่งขายที่ยังส่งไม่ครบ + วัตถุดิบที่ใบสั่งผลิตยังค้างเบิก + วัตถุดิบของใบสั่งตามแผนของระดับบน</li>
    <li>หักด้วยสต็อกในตำแหน่งที่ <b>นับเป็นยอดพร้อมใช้</b> (ทุกคลังรวมกัน เก็บสต็อกสำรองไว้) และ <b>กำหนดรับ</b> (ใบสั่งซื้อ ใบขอซื้อ ใบสั่งผลิตที่เปิดอยู่) — ใบที่สั่งไว้แล้วแต่มาช้า ยังนับครอบคลุมก่อน (ได้ข้อความเลื่อนเข้า) ไม่สั่งซ้ำ</li>
    <li>ที่ยังขาดเป็น <b>ความต้องการสุทธิ</b> → ได้ใบสั่งตามแผน จำนวนปัดตามขนาดสั่ง (เท่าที่ขาด ปัดทวีคูณ ขั้นต่ำ สูงสุดต่อใบ) กำหนดรับ = วันที่ขาด และ <b>ควรสั่งวันที่</b> = กำหนดรับ − ระยะเวลาสั่ง</li>
    <li>ใบสั่งตามแผนประเภทผลิต กระจายวัตถุดิบตามสูตรไปเป็นความต้องการของระดับถัดไป แล้วทำซ้ำจนถึงวัตถุดิบ</li>
</ol>
<p class="text-secondary">ผลของการรันอยู่จนรันครั้งถัดไป — มีใบสั่งขายใหม่หรือเอกสารเปลี่ยน ให้รัน MRP ใหม่ (ระบบใหญ่มักรันทุกคืน) เวลาที่รันล่าสุดและผู้รันแสดงมุมซ้ายบน</p>

<h3>ใบสั่งตามแผน (Planned Orders)</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">ควรสั่งวันที่</td><td>กำหนดรับ − ระยะเวลาสั่ง (วัน) ของสินค้า ถ้าเลยมาแล้วแสดงเป็นวันนี้</td></tr>
    <tr><td class="text-nowrap">กำหนดเสร็จ</td><td>วันที่ต้องมีของ — ป้าย <b>ล่าช้า</b> = วันนั้นผ่านไปแล้ว</td></tr>
    <tr><td class="text-nowrap">สำหรับ</td><td>เอกสารหรือสินค้าที่ทำให้ขาด เช่น เลขใบสั่งขาย เลขใบสั่งผลิต หรือรหัสสินค้าแม่</td></tr>
</table>

<h3>ข้อความแนะนำ (Action Messages)</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">ออกใบสั่ง</td><td>ใบสั่งตามแผนที่ถึงวันที่ควรสั่งแล้ว — สร้างใบขอซื้อหรือใบสั่งผลิตได้เลย (ตัวแดง = เลยวันที่ควรสั่ง)</td></tr>
    <tr><td class="text-nowrap">เลื่อนเข้า / เร่ง</td><td>ใบสั่งซื้อ ใบขอซื้อ หรือใบสั่งผลิตที่เปิดอยู่ กำหนดรับช้ากว่าวันที่ต้องใช้ — ตามผู้ขายหรือฝ่ายผลิตให้เร่ง (Reschedule in / Expedite)</td></tr>
    <tr><td class="text-nowrap">เลื่อนออก</td><td>ใบที่เปิดอยู่ยังไม่ต้องใช้จนถึงวันที่แนะนำ — เลื่อนกำหนดรับออกไปได้ ไม่ต้องรีบรับของมาเก็บ (Reschedule out)</td></tr>
    <tr><td class="text-nowrap">ยกเลิก</td><td>ใบที่เปิดอยู่ไม่มีความต้องการรองรับเลย — พิจารณายกเลิกหรือลดจำนวน (Cancel)</td></tr>
</table>

<h3>ตาราง MRP ตามสินค้า (MRP Record)</h3>
<p>ทุกสินค้าที่ MRP คิด ทั้งที่พอและไม่พอ เรียงตามระดับ คลิกแถวเพื่อเปิด: บรรทัดบนบอกข้อมูลการวางแผน (ระดับ สั่งล่วงหน้า ขนาดสั่ง สต็อกสำรอง ยอดในคลัง) แล้วเป็นตาราง MRP แบบในตำราแบ่งตามสัปดาห์ (ช่อง <b>ค้าง</b> = เลยกำหนดมาแล้ว)</p>
<table class="table table-sm">
    <tr><td class="text-nowrap">ความต้องการรวม</td><td>Gross Requirements — ทุกความต้องการของสัปดาห์นั้น</td></tr>
    <tr><td class="text-nowrap">กำหนดรับ</td><td>Scheduled Receipts — ใบสั่งซื้อ ใบขอซื้อ ใบสั่งผลิตที่เปิดอยู่</td></tr>
    <tr><td class="text-nowrap">ยอดคงคลังคาดการณ์</td><td>Projected On Hand — ยอดปลายสัปดาห์ = ยอดก่อนหน้า + กำหนดรับ + รับตามแผน − ความต้องการรวม (ตัวแดง = ต่ำกว่าสต็อกสำรอง)</td></tr>
    <tr><td class="text-nowrap">ความต้องการสุทธิ</td><td>Net Requirements — ส่วนที่ยังขาด (เทียบสต็อกสำรอง) หลังหักยอดคงคลังและกำหนดรับ</td></tr>
    <tr><td class="text-nowrap">รับตามแผน</td><td>Planned Order Receipts — ใบสั่งตามแผนที่ต้องได้ของสัปดาห์นั้น</td></tr>
    <tr><td class="text-nowrap">ออกใบสั่งตามแผน</td><td>Planned Order Releases — สัปดาห์ที่ต้องสั่ง (ถอยจากรับตามแผนเท่าระยะเวลาสั่ง) ของสินค้าผลิต จำนวนนี้ × สูตร = ความต้องการรวมของวัตถุดิบในระดับถัดไป</td></tr>
</table>
<p>ใต้ตารางคือ <b>ที่มาของแต่ละตัวเลข (MRP Detail)</b>: ทุกรายการเรียงตามวันที่ — ใบสั่งขาย, เบิกเข้าใบสั่งผลิต, ใช้ผลิตตามแผน, ใบสั่งซื้อ, ใบขอซื้อ, ใบสั่งผลิต, ใบสั่งตามแผน — พร้อมยอดคงเหลือหลังแต่ละรายการ</p>

<h3>ขั้นตอน</h3>
<ol>
    <li>กด <b>รัน MRP</b></li>
    <li>อ่าน <b>ข้อความแนะนำ</b>: ออกใบสั่ง → ข้อ 3–4; เลื่อนเข้า/เลื่อนออก/ยกเลิก → แก้ใบสั่งซื้อหรือใบสั่งผลิตนั้น (หรือแจ้งผู้ขาย)</li>
    <li>ติ๊กใบสั่งตามแผนประเภท <b>ซื้อ</b> แล้วกด <b>สร้างใบขอซื้อจากที่เลือก</b> — ได้ใบขอซื้อหนึ่งใบรวมทุกรายการ ราคาประมาณจากต้นทุนของสินค้า</li>
    <li>ติ๊กประเภท <b>ผลิต</b> แล้วกด <b>สร้างใบสั่งผลิตจากที่เลือก</b> — ได้ใบสั่งผลิตหนึ่งใบต่อรายการ (หรือหลายใบถ้าเกินสูงสุดต่อใบ) สถานะยังไม่เริ่มผลิต วัตถุดิบในใบตามสูตรเดียวกับที่ MRP กระจาย</li>
    <li>รายการที่สร้างเอกสารแล้วหายไปจากใบสั่งตามแผน และในตาราง MRP จะเห็นเป็นเอกสารนั้นทันที (กำหนดรับ / เบิกเข้าใบสั่งผลิต)</li>
</ol>
<p class="text-secondary">ระยะเวลาสั่งและขนาดสั่งตั้งที่ <b>สินค้าและวัตถุดิบ</b> สต็อกสำรองตั้งที่ <b>วางแผนสินค้าแยกสาขา</b></p>
