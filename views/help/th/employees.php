<h3>ผูกพนักงานกับผู้ใช้ ได้อะไร</h3>
<ul>
    <li>ใบขอซื้อใหม่ ช่องผู้ขอซื้อ และการตรวจคุณภาพใหม่ ช่องผู้ตรวจ ใส่ชื่อของคนที่ล็อกอินให้เอง (เปลี่ยนเป็นคนอื่นหรือพิมพ์ชื่อเองได้)</li>
    <li>แท็บ <b>แรงงาน</b> ในใบสั่งผลิต เลือกพนักงานของคนที่ล็อกอินไว้ก่อน</li>
</ul>

