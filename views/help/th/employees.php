<ol>
    <li>สร้างผู้ใช้ที่ <b>ตั้งค่าระบบ › ผู้ใช้</b> ก่อน (ถ้าคนนี้จะเข้าระบบ)</li>
    <li>กลับมาหน้านี้ กด <b>เพิ่ม</b> ใส่รหัส ชื่อ ศูนย์งานประจำ ค่าแรง แล้วเลือกผู้ใช้ที่เข้าระบบ</li>
</ol>
