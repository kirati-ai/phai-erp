<h3>ค่า SMTP เอามาจากไหน</h3>
<p><b>Gmail / Google Workspace</b></p>
<ul>
    <li>SMTP server <code>smtp.gmail.com</code> · พอร์ต <code>587</code> · การเข้ารหัส STARTTLS</li>
    <li>ชื่อผู้ใช้ = อีเมลผู้ส่ง</li>
    <li>รหัสผ่าน = <b>App Password</b> 16 ตัว (ไม่ใช่รหัสผ่านที่ใช้เข้า Gmail): เปิด Google Account → Security → เปิด "2-Step Verification" ก่อน → ค้นหา "App passwords" → สร้างใหม่ ตั้งชื่อเช่น PhaiERP → คัดลอกมาใส่</li>
</ul>
<p><b>Microsoft 365 / Outlook</b>: <code>smtp.office365.com</code> · พอร์ต <code>587</code> · STARTTLS (ผู้ดูแลต้องเปิด "Authenticated SMTP" ให้กล่องจดหมายนั้น)</p>
<p><b>อีเมลโดเมนบริษัทจากโฮสติ้ง</b>: ขอ SMTP server พอร์ต และการเข้ารหัสจากผู้ดูแลอีเมลหรือบริษัทโฮสติ้ง (มักเป็น <code>mail.ชื่อโดเมน</code> พอร์ต 465 SSL หรือ 587 STARTTLS)</p>

<h3>ขั้นที่ 3 ทดสอบแล้วบันทึก</h3>
<ol>
    <li>ใส่อีเมลของคุณเองในช่อง "อีเมลสำหรับทดสอบ" แล้วกด <b>ส่งทดสอบ</b> — อีเมลทดสอบไม่ส่งสำเนาถึง สพธอ.</li>
    <li>ได้รับอีเมลแล้วกด <b>บันทึก</b> ถ้าไม่ได้รับ ดูข้อความแจ้งข้อผิดพลาด แล้วตรวจชื่อผู้ใช้ รหัสผ่าน และพอร์ต</li>
    <li>ส่งใบกำกับภาษีจริงจากหน้าใบแจ้งหนี้ ปุ่ม e-Tax ดูประวัติการส่งที่ บัญชี → ลูกหนี้ → e-Tax Invoice (อีเมล)</li>
</ol>
<p class="text-secondary">รหัสผ่านเก็บในไฟล์ config.php บนเครื่องเซิร์ฟเวอร์ ไม่อยู่ในฐานข้อมูล และไม่แสดงกลับมาบนหน้านี้ — เว้นว่างไว้ตอนบันทึกเพื่อใช้รหัสเดิม</p>

<h3>กล่องล่าง: ใบรับรอง (เฉพาะแบบ XML)</h3>
<ul>
