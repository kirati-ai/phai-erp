<h3>หน้านี้คืออะไร</h3>
<p>เทียบ <b>รายการเงินเข้า-ออกในบัญชีธนาคารของระบบ</b> กับ <b>statement ของธนาคาร</b> ทุกสิ้นเดือน (หรือบ่อยกว่า) เพื่อหาเงินที่ยังไม่เข้า เช็คที่ยังไม่ขึ้น หรือรายการที่ลืมบันทึก ยอดเป็นเงินบาทของรหัสบัญชีที่ผูกกับบัญชีธนาคาร</p>
<p><b>บัญชีที่มีรายการรอกระทบยอด</b> ด้านบนแสดงบัญชีธนาคารที่มีรายการถึงวันนี้ยังไม่กระทบ จำนวนรายการ และวันที่กระทบล่าสุด (ซ่อนเมื่อไม่มี) กด <b>กระทบยอดธนาคาร</b> เพื่อเลือกบัญชีนั้น</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>รายการเงินเข้า-ออกที่ลงบัญชีธนาคาร (<b>รับชำระเงิน</b> <b>จ่ายชำระเจ้าหนี้</b> <b>สมุดรายวัน</b>) + statement ธนาคาร</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>รายการที่ลืมบันทึก (ค่าธรรมเนียม ดอกเบี้ย) ไปบันทึกใน <b>สมุดรายวัน</b></td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>งบกระทบยอดเงินฝากธนาคาร (Bank Reconciliation)</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — แค่จับคู่รายการที่ลงไว้แล้วกับ statement</td></tr>
</table>

<h3>ขั้นตอน</h3>
<ol>
    <li>เลือก <b>บัญชีรับ/จ่ายเงิน</b> และ <b>วันที่ statement</b> (ต้องหลังวันที่กระทบยอดครั้งก่อน)</li>
    <li>ระบบแสดงรายการในบัญชีที่ยังไม่เคยกระทบ ถึงวันที่ statement — ติ๊กทุกรายการที่ <b>ปรากฏใน statement</b> (คลิกทั้งแถวได้)</li>
    <li><b>ยอดหลังกระทบ</b> ด้านบน = ยอดกระทบครั้งก่อน + เงินเข้าที่เลือก − เงินออกที่เลือก ต้องตรงกับยอดคงเหลือใน statement จริง ตรงแล้วกด <b>บันทึก</b> (ยอดนี้เก็บเป็นยอดตาม statement ของครั้งนั้น)</li>
</ol>

<h3>ยอดหลังกระทบไม่ตรง statement</h3>
<ul>
    <li>รายการใน statement ที่ไม่มีในระบบ (ค่าธรรมเนียม ดอกเบี้ย เงินโอนที่ยังไม่บันทึกรับ) — บันทึกเอกสารหรือ <b>สมุดรายวัน</b> ก่อน เช่น ค่าธรรมเนียม: เดบิต <code>50802</code> ค่าธรรมเนียมธนาคาร / เครดิต บัญชีธนาคาร แล้วกลับมาติ๊ก</li>
    <li>ยอดไม่ตรง ตรวจจำนวนเงินในเอกสารต้นทาง</li>
</ul>
<p>รายการที่ไม่ได้ติ๊ก (เงินฝากระหว่างทาง เช็คที่ผู้รับยังไม่นำไปขึ้น) ค้างไว้ให้ติ๊กในครั้งถัดไป</p>

<h3>ประวัติ พิมพ์ ยกเลิก</h3>
<p>ใต้ตารางมีรายการกระทบยอดที่บันทึกแล้ว ปุ่มพิมพ์ให้ <b>งบกระทบยอดเงินฝากธนาคาร</b>: ยอดตาม statement + เงินฝากระหว่างทาง − รายการจ่ายที่ธนาคารยังไม่ลง = ยอดตามบัญชี — ยกเลิก (ย้อนกลับ) ได้เฉพาะ <b>ครั้งล่าสุด</b> แล้วรายการของครั้งนั้นกลับมาให้ติ๊กใหม่</p>
<p class="text-secondary">ครั้งแรกยอดกระทบครั้งก่อนเป็น 0 จึงต้องติ๊กรายการตั้งแต่ยอดยกมาด้วย การกระทบยอดไม่ลงบัญชีใด ๆ</p>

<h3>เอกสารแนบ</h3>
<p>กดรูปคลิปในแถวประวัติการกระทบยอด เปิดหน้าต่าง <b>เอกสารแนบ</b> ของครั้งนั้น (คลิปสีเขียวพร้อมตัวเลข = จำนวนไฟล์): กด <b>แนบไฟล์</b> แนบรูปหรือ PDF ได้หลายไฟล์ เช่น Statement ของธนาคารงวดนี้ — คลิกเพื่อเปิด กด × เพื่อลบ</p>
<p class="text-secondary">แนบต้องมีสิทธิ์เพิ่มหรือแก้ไขของหน้านี้ ลบต้องมีสิทธิ์แก้ไขหรือลบ แนบได้ทุกสถานะ ยกเลิกการกระทบยอดแล้วไฟล์แนบของครั้งนั้นถูกลบด้วย</p>
