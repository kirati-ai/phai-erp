<h3>ข้อควรรู้เรื่องวัตถุดิบ</h3>
<ul>
    <li>ช่อง <b>ผู้ขาย / ลูกค้า</b> ของวัตถุดิบเลือกจาก <b>ผู้ขาย</b> หลักที่ซื้อของนี้</li>
    <li>วัตถุดิบขายตรงไม่ได้ ต้องแปลงเป็นสินค้า FG ก่อน (ปุ่ม <b>แปลงเป็น FG</b> ในหน้าดูแถวสต็อก)</li>
    <li>ต้นทุนวัตถุดิบมาจากราคาที่รับเข้า (ถัวเฉลี่ย)</li>
</ul>
