<h3>ปรับราคา (สินค้า FG)</h3>
<p>เปลี่ยนต้นทุนต่อหน่วยของสินค้า เช่น ต้นทุนเดิมสูงเกินจริง ทุกคลัง/ตำแหน่ง/ล็อตที่มีของ จะออกด้วยราคาเดิมและเข้าด้วยราคาใหม่ จำนวนไม่เปลี่ยน</p>
<ol>
    <li>ใส่วันที่ (ไม่เกินวันนี้) เลือก <b>เหตุผล</b> ถ้าต้องการให้ผลต่างลงบัญชีของรหัสเหตุผลนั้น (ไม่เลือก = บัญชีปรับปรุงสินค้า)</li>
    <li>ใส่สินค้า ระบบแสดง <b>มีอยู่</b> และ <b>ราคาเดิม</b> ใส่ <b>ราคาใหม่/หน่วย</b></li>
    <li>กด <b>เพิ่มบรรทัด</b> ถ้ามีหลายสินค้า แล้วกด <b>บันทึก</b></li>
</ol>
<p class="text-secondary">วัตถุดิบ (RM) ปรับราคาไม่ได้ ใช้ราคาที่รับเข้า · ราคาใหม่ต้องไม่เท่าราคาเดิม และสินค้าต้องมีสต็อก</p>

