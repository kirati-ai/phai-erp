<h3>หน้านี้คืออะไร</h3>
<p>รายชื่อ <b>รหัสบัญชี</b> ทั้งหมดของบริษัท ทุกเอกสารลงบัญชีด้วยรหัสในหน้านี้ ติดตั้งใหม่มีผังบัญชีมาตรฐานให้แล้ว (เช่น <code>10101</code> เงินสดในมือ, <code>11101</code> ลูกหนี้การค้า, <code>40101</code> รายได้จากการขาย) เพิ่มหรือแก้ชื่อได้ตามธุรกิจ</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>ผังบัญชีมาตรฐานที่ติดตั้งมา ปรับตามธุรกิจ</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>ทุกเอกสารที่ลงบัญชี · <b>ตั้งค่าบัญชี</b> · <b>งบทดลอง</b></td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>ผังบัญชี (Chart of Accounts) — ข้อมูลหลัก</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — เป็นรหัสที่รายการบัญชีใช้</td></tr>
</table>

