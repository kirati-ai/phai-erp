    <tr><td class="text-nowrap">ใช้งาน</td><td>ปิดเมื่อเลิกใช้ — รายการเก่ายังอยู่ แต่เลือกในเอกสารใหม่ไม่ได้</td></tr>
</table>

<h3>เพิ่มบัญชีใหม่</h3>
<ol>
    <li>กด <b>เพิ่ม</b> ใส่รหัส เลือกหมวด ใส่ชื่อ แล้ว <b>บันทึก</b></li>
    <li>ใช้รหัสนั้นได้ทันทีใน สมุดรายวัน ตั้งหนี้ (ค่าใช้จ่ายอื่น) บัญชีธนาคาร และหน้าตั้งค่าที่ต้องเลือกบัญชี</li>
</ol>
<p class="text-secondary">ลบได้เฉพาะบัญชีที่ยังไม่เคยมีรายการ และไม่ถูกใช้ในบัญชีธนาคาร รหัสภาษีหัก ณ ที่จ่าย หรือสินทรัพย์ถาวร — บัญชีที่เคยใช้แล้วให้ปิด "ใช้งาน" แทน</p>

<h3>บัญชีที่ระบบใช้เอง</h3>
<p>บัญชีลูกหนี้ เจ้าหนี้ ภาษีซื้อ ภาษีขาย ฯลฯ ที่เอกสารลงให้อัตโนมัติ กำหนดที่ <b>ตั้งค่าบัญชี</b> ส่วนบัญชีสินค้า ขาย ต้นทุนขาย ตามประเภทสินค้า กำหนดที่ <b>ข้อมูลหลัก → สายผลิตภัณฑ์</b> แท็บบัญชี</p>
