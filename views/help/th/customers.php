<h3>วงเงินเครดิต</h3>
<p>ถ้าเปิด <b>ตรวจวงเงินเครดิต</b> ในหน้า <b>ตั้งค่าการขาย</b> ตอนบันทึกใบสั่งขาย ระบบรวม ลูกหนี้ค้างชำระ + ยอดที่สั่งแล้วยังไม่ออกใบแจ้งหนี้ (รวม VAT เป็นบาท) + ใบนี้ ถ้าเกินวงเงินจะ <b>บันทึกได้แต่ขึ้นคำเตือน</b> ไม่ถูกบล็อก</p>
<p class="text-secondary">ลูกค้าที่มีเอกสารแล้ว (ใบเสนอราคา ใบสั่งขาย ใบส่งของ ใบแจ้งหนี้ รับชำระ ใบวางบิล) ลบไม่ได้ ระบบจะแจ้ง "ลบไม่ได้ ข้อมูลนี้ถูกใช้งานอยู่" — ให้เปลี่ยนสถานะเป็น เลิกใช้ แทน เอกสารเก่ายังอ้างถึงได้</p>

