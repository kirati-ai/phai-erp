<h3>หน้านี้คืออะไร</h3>
<p><b>งบทดลอง</b> ของช่วงวันที่ที่เลือก: แต่ละบัญชีแสดง ยกมา เดบิต เครดิต และยกไป ยอดรวมเดบิตต้องเท่ากับเครดิตเสมอ (ถ้าไม่เท่าจะขึ้นคำว่า "ไม่สมดุล") — และเป็นที่ <b>ปิดงวด</b> บัญชี</p>
<p><b>งวดที่สิ้นเดือนแล้ว รอปิดงวด</b> ขึ้นด้านบนเมื่องวดที่เปิดอยู่สิ้นเดือนแล้ว (เฉพาะผู้มีสิทธิ์ปิดงวด) กด <b>ปิดงวด</b> แล้วยืนยัน</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>ทุกรายการใน <b>สมุดรายวัน</b></td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>ปิดงวด แล้วจัดทำงบการเงิน</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>งบทดลอง (Trial Balance) — รายงาน ไม่ใช่เอกสาร</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — ปิดงวดแค่เลื่อนงวดที่เปิด (ต้องลงค่าเสื่อมของเดือนให้ครบก่อน)</td></tr>
</table>

<h3>อ่านตัวเลข</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">ยกมา / ยกไป</td><td>ยอดคงเหลือก่อนและหลังช่วง — บวก = ด้านเดบิต, ลบ = ด้านเครดิต (หนี้สิน ทุน รายได้ ปกติติดลบ)</td></tr>
    <tr><td class="text-nowrap">รายได้ / ค่าใช้จ่าย</td><td>เริ่มที่ศูนย์ทุกวันที่ 1 มกราคม (ปีบัญชี = ปีปฏิทิน) กำไรขาดทุนของปีก่อนแสดงรวมใน <b>บัญชีกำไรสะสม</b></td></tr>
</table>

<h3>ดูรายละเอียด</h3>
<ol>
    <li>เลือกช่วงวันที่ (ค่าเริ่มต้น: ต้นงวดที่เปิดถึงวันนี้)</li>
    <li>คลิกบัญชีเพื่อเปิด <b>บัญชีแยกประเภท</b>: ทุกรายการในช่วง พร้อมศูนย์ต้นทุนและยอดคงเหลือสะสม</li>
    <li>คลิกรายการเพื่อเปิดรายการบัญชีนั้นในสมุดรายวัน</li>
</ol>

<h3>ปิดงวด</h3>
<p><b>งวดที่เปิด</b> แสดงข้างปุ่ม ทุกเอกสารลงวันที่ก่อนวันที่ 1 ของงวดที่เปิดไม่ได้ เมื่อสิ้นเดือนและตรวจยอดเรียบร้อยแล้ว (กระทบยอดธนาคาร ลงค่าเสื่อม ตรวจรายงานภาษี) กด <b>ปิดงวด</b> — ถ้ายังมีสินทรัพย์ที่ค่าเสื่อมของเดือนนั้นยังไม่ลง ระบบไม่ให้ปิด เพราะปิดแล้วจะลงค่าเสื่อมของเดือนนั้นไม่ได้อีก</p>
<ul>
    <li>ปิดได้ทีละเดือน และเฉพาะเดือนที่สิ้นสุดแล้ว</li>
    <li>หลังปิด ลงรายการย้อนหลังในเดือนนั้นไม่ได้ — การยกเลิกเอกสารเก่าหลังจากนี้ ระบบกลับรายการลงวันที่ในงวดที่เปิด</li>
    <li>ต้องมีสิทธิ์แก้ไขของหน้างบทดลอง</li>
</ul>
<p class="text-secondary">ปิดงวดแล้วเปิดกลับไม่ได้ ตรวจให้ครบก่อนกดยืนยัน</p>
