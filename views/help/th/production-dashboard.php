<h3>หน้านี้ใช้ทำอะไร</h3>
<p>สรุปงานผลิต: <b>ต้องผลิตอะไร เท่าไร ให้ใคร</b> (ตามใบสั่งขาย) ใบสั่งผลิตที่กำลังทำ ใบที่รอเริ่มผลิต งานที่เสร็จเดือนนี้ และผลตรวจคุณภาพ</p>

<h3>ผลิตในระบบ ERP</h3>
<p>โมดูลผลิตคือ <b>Manufacturing</b> คู่กับ <b>MRP</b> (Material Requirements Planning การวางแผนความต้องการวัสดุ) — กำหนดสูตร วางแผนว่าจะซื้อหรือผลิตอะไร แล้วคุมการผลิตและต้นทุนจริง (วัตถุดิบ + ค่าแรง + โสหุ้ย)</p>

<h3>สายเอกสาร</h3>
<ol>
    <li><b>ข้อมูลตั้งต้น</b>: สูตรการผลิต (BOM) + ขั้นตอน (Routing) ศูนย์งาน เครื่องจักร พนักงาน และวางแผนสินค้าแยกสาขา (สต็อกสำรอง)</li>
    <li><b>วางแผนวัตถุดิบ (MRP)</b> — ดูใบสั่งขายค้างส่ง สต็อก ของที่สั่งไว้ แล้วแนะนำให้สร้างใบขอซื้อหรือใบสั่งผลิต — ผู้วางแผนกด <b>รัน MRP</b> ได้ใบสั่งตามแผน ข้อความแนะนำ และตาราง MRP ต่อสินค้า</li>
    <li><b>ใบสั่งผลิต</b> (Work Order) สถานะ F แก้ได้ → R เริ่มผลิต</li>
    <li>เบิกวัตถุดิบ — Dr งานระหว่างทำ (WIP) / Cr วัตถุดิบ</li>
    <li>บันทึกแรงงาน — Dr งานระหว่างทำ / Cr ค่าแรงทางตรง / Cr โสหุ้ยการผลิตที่ปันส่วน</li>
    <li>รับเข้าคลัง + ใบตรวจคุณภาพ (QC) — Dr สินค้า FG / Cr งานระหว่างทำ</li>
    <li>ปิดงาน (C) — WIP ที่เหลือเป็นผลต่างการผลิต เข้าต้นทุนขาย</li>
</ol>

<h3>ส่งต่อโมดูลอื่น</h3>
<ul>
    <li><b>ขาย</b>: ใบสั่งขายค้างส่งเป็นความต้องการของ MRP และสินค้าที่ผลิตเสร็จพร้อมส่งของ</li>
    <li><b>จัดซื้อ</b>: MRP สร้างใบขอซื้อวัตถุดิบที่ขาด</li>
    <li><b>คลังสินค้า</b>: เบิกวัตถุดิบและรับผลผลิตผ่านคลังทุกครั้ง</li>
    <li><b>บัญชี</b>: ต้นทุนการผลิตลงสมุดรายวันประเภท WO</li>
</ul>

