<h3>หน้านี้ใช้ทำอะไร</h3>
<p><b>ใบส่งคืนสินค้า</b> บันทึกของที่ส่งคืนผู้ขาย (ชำรุด ผิดสเปก ส่งเกิน) จากใบรับสินค้าใบหนึ่ง ระบบตัดสต็อกออก และรอใบลดหนี้จากผู้ขาย</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td><b>รับสินค้าเข้าคลัง</b> — เปิดใบรับแล้วกด <b>ส่งคืนสินค้า</b> คืนได้ไม่เกินที่รับมาลบที่คืนไปแล้ว</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td><b>ตั้งหนี้</b>: ถ้ายังไม่ได้ตั้งหนี้ของใบรับ ให้ติ๊กใบส่งคืนพร้อมใบรับ (หักจากใบแจ้งหนี้) — ถ้าตั้งหนี้แล้ว ผู้ขายจะออก <b>ใบลดหนี้</b> มา กด <b>บันทึกใบลดหนี้ของผู้ขาย</b> เป็นตั้งหนี้ชนิดใบลดหนี้ที่ดึงใบส่งคืนนี้ไปเอง</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>ใบส่งคืนสินค้า (Purchase return / Return to vendor) — หลักฐานภาษีคือ <b>ใบลดหนี้</b> ที่ผู้ขายออกให้ (ม.86/10) ใช้ลดภาษีซื้อในเดือนที่ได้รับ</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ส่งคืน: Dr สินค้ารับแล้วรอใบแจ้งหนี้ (ราคาซื้อ) / Cr สินค้าคงคลัง (ต้นทุนถัวเฉลี่ย) / ผลต่างเข้าบัญชีปรับปรุงสินค้า — ใบลดหนี้ของผู้ขาย: Dr เจ้าหนี้ / Cr สินค้ารับแล้วรอใบแจ้งหนี้, Cr ภาษีซื้อ</td></tr>
</table>

<h3>ใช้งาน</h3>
<ol>
    <li>เปิดใบรับสินค้า กด <b>ส่งคืนสินค้า</b> (หรือเลือกจากรายการใบรับที่ยังคืนได้ในหน้าใหม่ ค้นด้วยเลขที่ ผู้ขาย เลข PO หรือเลขใบส่งของผู้ขาย)</li>
    <li>ใส่ <b>เหตุผลที่ส่งคืน</b> และ <b>จำนวนที่คืน</b> ของบรรทัดที่คืน (ของออกจากตำแหน่งและล็อตเดิมที่รับเข้า ต้องยังมีของพอ)</li>
    <li>บันทึก — สถานะ <b>รอใบลดหนี้</b> → เมื่อนำไปหักในตั้งหนี้หรือใบลดหนี้แล้วเป็น <b>หักหนี้แล้ว</b> (ยกเลิกตั้งหนี้นั้น ใบส่งคืนกลับมารอ)</li>
    <li>กด <b>พิมพ์ / PDF</b> ส่งไปพร้อมของ ให้ผู้ขายเซ็นรับคืน</li>
</ol>
<p class="text-secondary">ใบสั่งซื้อไม่เปิดกลับให้อัตโนมัติ ถ้าผู้ขายจะส่งของมาแทน ให้ออกใบสั่งซื้อใหม่</p>

<h3>เอกสารแนบ</h3>
<p>หัวข้อ <b>เอกสารแนบ</b> ใต้เอกสารที่บันทึกแล้ว: กด <b>แนบไฟล์</b> แนบรูปหรือ PDF ได้หลายไฟล์ เช่น รูปของชำรุด ใบลดหนี้ของผู้ขาย หนังสือแจ้งคืน — คลิกเพื่อเปิด กด × เพื่อลบ — กดรูปคลิปท้ายแถวในหน้ารายการ เปิดหน้าต่างเอกสารแนบของแถวนั้นได้เลยโดยไม่ต้องเปิดเอกสาร (คลิปสีเขียวพร้อมตัวเลข = จำนวนไฟล์ที่แนบไว้)</p>
<p class="text-secondary">แนบต้องมีสิทธิ์เพิ่มหรือแก้ไขของหน้านี้ ลบต้องมีสิทธิ์แก้ไขหรือลบ แนบได้ทุกสถานะ</p>
