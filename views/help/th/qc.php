<h3>ขั้นตอน</h3>
<ol>
    <li>กด <b>เพิ่ม</b> เลือกผล ใส่รหัสสินค้า ล็อต และเอกสารอ้างอิง</li>
    <li>ใส่จำนวนที่ตรวจและหมายเหตุ แล้วบันทึก — ตรวจให้ถูกก่อนบันทึก เพราะบันทึกแล้วแก้ไม่ได้</li>
    <li>กดไอคอน <b>พิมพ์</b> ท้ายแถว ได้ใบตรวจคุณภาพสินค้า (QC) ให้ผู้ตรวจและผู้อนุมัติเซ็น</li>
    <li>ค้นหาย้อนหลังได้ด้วยเลขที่ เอกสารอ้างอิง (เช่น เลขใบสั่งผลิต) รหัสสินค้า หรือล็อต — คลิกเลขใบ QC ในแท็บรับผลผลิตของใบสั่งผลิตก็เปิดมาที่หน้านี้</li>
</ol>
<p class="text-secondary">ถ้าของไม่ผ่านและต้องกันไว้ไม่ให้ใช้ เปลี่ยนสถานะของแถวสต็อกนั้นที่หน้า <b>ยอดคงเหลือสินค้า</b> หรือ <b>สต็อกวัตถุดิบ</b> (คลิกแถว → แก้ไข)</p>

