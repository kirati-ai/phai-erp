<h3>หน้านี้คืออะไร</h3>
<p><b>บทบาท</b> คือชุดสิทธิ์ตามหน้าที่งาน เช่น ฝ่ายขาย ฝ่ายจัดซื้อ ฝ่ายบัญชี — ผู้ใช้หนึ่งคนมีหนึ่งบทบาท (ตั้งในหน้า <b>ผู้ใช้</b>) แล้วเห็นเฉพาะเมนูและข้อมูลที่บทบาทนั้นมีสิทธิ์ รวมถึงคำตอบของ <b>ถาม AI</b></p>
<p>ด้านซ้ายคือรายชื่อบทบาท ด้านขวาคือตารางสิทธิ์ของบทบาทที่เลือก แยกตามหมวดเมนู</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>รายการหน้าจอ (โปรแกรม) ของระบบ</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td><b>ผู้ใช้</b> แต่ละคนมีหนึ่งบทบาท → เมนู หน้าจอ API และ AI ที่เห็น</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>บทบาทและสิทธิ์ (Role-Based Access Control) — ใช้แบ่งแยกหน้าที่ เช่น คนสั่งซื้อไม่ใช่คนจ่ายเงิน</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี</td></tr>
</table>

<h3>สิทธิ์แต่ละช่อง</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">ดู</td><td>เปิดหน้านั้นและเห็นข้อมูล — ไม่ติ๊ก เมนูนั้นจะไม่แสดง</td></tr>
    <tr><td class="text-nowrap">เพิ่ม / แก้ / ลบ</td><td>สร้างรายการใหม่ แก้ไข และลบ (หรือยกเลิกเอกสาร) ในหน้านั้น — สิทธิ์ แก้ ยังรวมการกระทำสำคัญของหน้านั้น: ปรับยอดตามตรวจนับ ปันส่วนค่าใช้จ่ายนำเข้า ขึ้นทะเบียน/ลงค่าเสื่อม/จำหน่ายสินทรัพย์ และปิดงวดบัญชี (ไม่มีสิทธิ์อนุมัติแยก)</td></tr>
    <tr><td class="text-nowrap">พิมพ์</td><td>พิมพ์เอกสารและบันทึก PDF</td></tr>
</table>
<p>ติ๊กสิทธิ์ใดก็ตาม ระบบติ๊ก <b>ดู</b> ให้เอง เอาติ๊ก <b>ดู</b> ออก สิทธิ์อื่นของหน้านั้นจะหลุดด้วย — ช่องติ๊กบนหัวคอลัมน์ใช้ติ๊กหรือเอาออกทั้งคอลัมน์ และช่องติ๊กในแถวชื่อหมวด (เช่น ข้อมูลหลัก จัดซื้อ) ใช้ติ๊กหรือเอาออกเฉพาะหน้าจอในหมวดนั้น</p>

<h3>สร้างบทบาทใหม่</h3>
<ol>
    <li>กด <b>เพิ่ม</b> ใส่รหัสบทบาท (เช่น <code>SALES</code>) และชื่อบทบาท (เช่น "ฝ่ายขาย") แล้วกด <b>บันทึก</b></li>
    <li>คลิกบทบาทนั้นทางซ้าย ติ๊กสิทธิ์ของแต่ละหน้าทางขวา</li>
    <li>กด <b>บันทึก</b> ด้านบนตารางสิทธิ์ (ติ๊กแล้วยังไม่มีผลจนกดบันทึก)</li>
    <li>ไปที่ <b>ผู้ใช้</b> เลือกบทบาทนี้ให้พนักงาน</li>
</ol>
<p class="text-secondary">บทบาท <code>ADMIN</code> มีสิทธิ์ทุกหน้าเสมอ แก้หรือลบไม่ได้ — แก้ชื่อหรือปิดใช้งานบทบาทอื่นได้จากไอคอนดินสอข้างชื่อบทบาท บทบาทที่ปิดใช้งานจะไม่ขึ้นให้เลือกในหน้าผู้ใช้</p>
