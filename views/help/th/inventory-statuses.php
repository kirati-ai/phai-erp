<h3>สถานะของแถวสต็อก</h3>
<p>สถานะที่ติดกับสต็อกแต่ละแถว (ล็อต/ตำแหน่ง) ตั้งที่หน้า <b>ยอดคงเหลือ</b> › คลิกแถว › <b>แก้ไข</b> ช่อง <b>สถานะ</b> มี 4 ค่าคงที่: ใช้งาน, พักไว้, หมดอายุ, รอตรวจ — ไม่ได้มาจากรายการในหน้านี้</p>
