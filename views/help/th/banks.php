<h3>หน้านี้คืออะไร</h3>
<p>รายการ <b>ช่องทางเงิน</b> ที่บริษัทใช้รับและจ่ายเงิน — เงินสด และบัญชีธนาคารแต่ละบัญชี ใช้เลือกในหน้า <b>รับชำระเงิน</b>, <b>จ่ายชำระเจ้าหนี้</b> และ <b>กระทบยอดธนาคาร</b></p>
<p>แต่ละรายการผูกกับ <b>รหัสบัญชี</b> ในผังบัญชี ระบบลงบัญชีเงินเข้า/ออกที่รหัสนั้นให้เอง เช่น รับเงินเข้า BANK1 = เดบิต 10201</p>
<p>ตารางแสดง <b>ยอดคงเหลือ</b> ณ วันนี้ (ยอดของรหัสบัญชีในบัญชีแยกประเภท) <b>กระทบยอดล่าสุด</b> และจำนวนรายการที่ <b>รอกระทบ</b> — คลิกแถวเปิด <b>สมุดบัญชีเงินฝาก</b> ของบัญชีนั้น (แถวเงินสดย่อยไปหน้า <b>เงินสดย่อย</b>) ไอคอนดินสอเปิดฟอร์มตั้งค่า</p>

