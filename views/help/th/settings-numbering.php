<h3>หน้านี้คืออะไร</h3>
<p>รวมเลขที่เอกสารของทุกหมวดไว้ที่เดียว (หน้าตั้งค่าของแต่ละหมวด — จัดซื้อ คลังสินค้า ผลิต ขาย บัญชี — มีตารางเดียวกันเฉพาะเอกสารของหมวดนั้น) กำหนดว่าเลขที่ของเอกสารแต่ละชนิด (ใบสั่งซื้อ ใบแจ้งหนี้ ใบเสร็จ ฯลฯ) หน้าตาเป็นแบบไหน และเลขถัดไปคือเท่าไร ระบบออกเลขให้เองตอนกดบันทึกเอกสาร ไม่ต้องพิมพ์เอง</p>

