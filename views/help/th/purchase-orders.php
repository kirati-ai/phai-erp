<h3>หน้านี้ใช้ทำอะไร</h3>
<p><b>ใบสั่งซื้อ (PO)</b> ส่งให้ผู้ขายเพื่อสั่งของ เป็นเอกสารที่ใช้ <b>รับสินค้าเข้าคลัง</b> และตั้งหนี้ต่อ — ไม่มีขั้นอนุมัติในระบบ บันทึกแล้วรับของได้ทันที ถ้าต้องให้ผู้มีอำนาจเซ็น ให้กด <b>พิมพ์</b> ไปเซ็นก่อนส่งผู้ขาย</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td><b>ใบขอซื้อ</b> หรือสร้างเอง (ถ้า <b>ตั้งค่าจัดซื้อ</b> ไม่บังคับ)</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td><b>รับสินค้าเข้าคลัง</b> → <b>ตั้งหนี้เจ้าหนี้</b></td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>ใบสั่งซื้อ (Purchase Order, PO) — ข้อตกลงซื้อกับผู้ขาย ไม่ใช่เอกสารภาษี</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — เป็นคำสั่งซื้อ ยังไม่ได้รับของ (ลงบัญชีตอนรับสินค้า)</td></tr>
</table>

<h3>ช่องที่ควรรู้</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">ผู้ขาย</td><td>เลือกได้เฉพาะผู้ขายที่สถานะ ใช้งาน เลือกแล้วระบบเติม เงื่อนไขชำระ สกุลเงิน และภาษี จากทะเบียนผู้ขาย</td></tr>
    <tr><td class="text-nowrap">กำหนดส่ง</td><td>วันที่ผู้ขายต้องส่งของ</td></tr>
    <tr><td class="text-nowrap">รับเข้าคลัง</td><td>คลังที่จะรับของ</td></tr>
    <tr><td class="text-nowrap">สกุลเงิน / อัตราแลกเปลี่ยน</td><td>ซื้อต่างประเทศเลือกสกุล เช่น USD ระบบเติมอัตราตามวันที่เอกสาร (แก้ได้) ต้นทุนสินค้าคิดเป็นบาทด้วยอัตรานี้</td></tr>
    <tr><td class="text-nowrap">ภาษี</td><td>เช่น VAT 7% — <b>ราคาในบรรทัดไม่รวม VAT</b> ระบบบวกภาษีในยอดรวมให้</td></tr>
    <tr><td class="text-nowrap">ราคา/หน่วย</td><td>ระบบเติมราคาซื้อครั้งล่าสุดจากผู้ขายนี้ พิมพ์ทับได้</td></tr>
    <tr><td class="text-nowrap">ส่วนลด %</td><td>ส่วนลดต่อบรรทัด เช่น <code>5</code> = ลด 5%</td></tr>
    <tr><td class="text-nowrap">รับแล้ว</td><td>จำนวนที่รับเข้าคลังแล้วของบรรทัดนั้น</td></tr>
    <tr><td class="text-nowrap">ประเภทใบสั่ง</td><td><b>ปกติ</b> = ส่งครั้งเดียวตามกำหนดส่ง · <b>แบบกำหนดส่ง</b> = สัญญาราคาระยะยาว ของมาหลายงวด — บันทึกแล้วกด <b>ตารางกำหนดส่ง</b> เพื่อแบ่งงวด รับครบทุกงวดแล้วใบสั่งยังเปิดอยู่จนกด <b>ปิด</b></td></tr>
</table>

<h3>สั่งซื้อแล้วรับของ</h3>
<ol>
    <li>กด <b>เพิ่ม</b> (หรือ <b>สร้างใบสั่งซื้อ</b> จากใบขอซื้อ) เลือกผู้ขาย แล้วเพิ่มบรรทัดสินค้า จำนวน ราคา</li>
    <li>กด <b>บันทึก</b> แล้ว <b>พิมพ์</b> ส่งผู้ขาย</li>
    <li>ของมาถึง กด <b>รับสินค้า</b> ในใบสั่งซื้อ ไปหน้ารับสินค้าที่เลือกใบนี้ไว้ให้</li>
    <li>รับแล้ว ด้านขวาแสดง <b>ประวัติรับสินค้า</b> คลิกเปิดใบรับได้</li>
</ol>

<h3>สถานะ และสิ่งที่ทำได้</h3>
<ul>
    <li><b>เปิด</b> — รอรับของ แก้ไขได้ <b>เฉพาะก่อนรับของครั้งแรก</b> รับแล้วแก้ไม่ได้</li>
    <li><b>ปิดแล้ว</b> — รับครบทุกบรรทัด ระบบปิดให้เอง หรือกด <b>ปิดใบสั่งซื้อ</b> เมื่อผู้ขายส่งไม่ครบและจะไม่ส่งอีก (ส่วนที่ค้างจะไม่รอรับ)</li>
    <li><b>ยกเลิก</b> — กด <b>ยกเลิกเอกสาร</b> ได้เฉพาะยังไม่ได้รับของ ถ้าสร้างจากใบขอซื้อ ใบขอซื้อกลับเป็น เปิด</li>
</ul>
<p class="text-secondary">เหนือรายการมีกล่อง <b>ใบขอซื้อรอสั่งซื้อ</b> (แสดงเมื่อมีรายการ แถวสีแดง = เลยวันที่ต้องการใช้) กด <b>สร้างใบสั่งซื้อ</b> ได้ใบสั่งซื้อแยกตามผู้ขายแล้วเปิดใบแรก — บรรทัดที่ไม่ได้ระบุผู้ขายไปที่ผู้ขายในช่อง ผู้ขาย ของกล่อง ถ้าช่องนั้นว่าง ให้เปิดใบขอซื้อแล้วกดสร้างใบสั่งซื้อจากในนั้น</p>
<p class="text-secondary">ถ้าตั้งค่าจัดซื้อไว้ว่า "ใบสั่งซื้อต้องสร้างจากใบขอซื้อเท่านั้น" จะไม่มีปุ่มเพิ่มในหน้านี้ ให้สร้างจาก <b>ใบขอซื้อ</b></p>

<h3>เอกสารแนบ</h3>
<p>หัวข้อ <b>เอกสารแนบ</b> ใต้เอกสารที่บันทึกแล้ว: กด <b>แนบไฟล์</b> แนบรูปหรือ PDF ได้หลายไฟล์ เช่น ใบเสนอราคาที่ใช้สั่ง สัญญา ใบสั่งซื้อที่ผู้ขายเซ็นตอบรับ — คลิกเพื่อเปิด กด × เพื่อลบ — กดรูปคลิปท้ายแถวในหน้ารายการ เปิดหน้าต่างเอกสารแนบของแถวนั้นได้เลยโดยไม่ต้องเปิดเอกสาร (คลิปสีเขียวพร้อมตัวเลข = จำนวนไฟล์ที่แนบไว้)</p>
<p class="text-secondary">แนบต้องมีสิทธิ์เพิ่มหรือแก้ไขของหน้านี้ ลบต้องมีสิทธิ์แก้ไขหรือลบ แนบได้ทุกสถานะ</p>
