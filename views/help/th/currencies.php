<h3>หน้านี้คืออะไร</h3>
<p>รายการ <b>สกุลเงิน</b> ที่ใช้ในเอกสารซื้อขาย เช่น THB, USD — เลือกเป็นสกุลเงินของลูกค้า ผู้ขาย และเอกสาร สกุลเงินหลักของบริษัทตั้งที่ <b>ข้อมูลบริษัท</b> (ปกติ THB)</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>สกุลเงินมาตรฐาน ISO 4217 ที่ติดตั้งมา</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td><b>อัตราแลกเปลี่ยน</b> · ลูกค้า ผู้ขาย และเอกสารซื้อขาย</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>สกุลเงิน (Currency) — ข้อมูลหลัก</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — ลูกหนี้ เจ้าหนี้ และบัญชีแยกประเภทเก็บเป็นบาทเสมอ</td></tr>
</table>

<h3>ช่องต่าง ๆ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">รหัส</td><td>รหัส 3 ตัวอักษรตามมาตรฐานสากล เช่น <code>USD</code>, <code>EUR</code>, <code>JPY</code></td></tr>
    <tr><td class="text-nowrap">ชื่อสกุลเงิน</td><td>เช่น "US Dollar", "ดอลลาร์สหรัฐ"</td></tr>
    <tr><td class="text-nowrap">สัญลักษณ์</td><td>เช่น <code>$</code>, <code>€</code>, <code>฿</code></td></tr>
    <tr><td class="text-nowrap">ใช้งาน</td><td>ปิดเมื่อเลิกใช้ — จะไม่ขึ้นให้เลือกในรายการใหม่</td></tr>
</table>

<h3>ใช้สกุลเงินต่างประเทศ</h3>
<ol>
    <li>ตรวจว่ามีสกุลเงินนั้นในหน้านี้ ถ้าไม่มี กด <b>เพิ่ม</b></li>
    <li>ไปที่ <b>อัตราแลกเปลี่ยน</b> ใส่อัตราเป็นบาทต่อ 1 หน่วยของสกุลนั้น</li>
    <li>ตั้งสกุลเงินที่ลูกค้าหรือผู้ขาย เอกสารใหม่จะใช้สกุลนั้นและแปลงเป็นบาทตามอัตราของวันที่เอกสาร</li>
</ol>
<p class="text-secondary">สกุลเงินที่ลูกค้า ผู้ขาย หรืออัตราแลกเปลี่ยนใช้อยู่ ลบไม่ได้ — ลูกหนี้และเจ้าหนี้ในระบบเก็บเป็นเงินบาทเสมอ</p>
