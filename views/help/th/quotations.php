<h3>หน้านี้ใช้ทำอะไร</h3>
<p>เสนอราคาให้ลูกค้า พิมพ์ส่งไปเซ็น เมื่อลูกค้าตกลง กดปุ่มเดียวได้ใบสั่งขาย ไม่ต้องคีย์ซ้ำ</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td><b>ลูกค้า</b> <b>สินค้าและวัตถุดิบ</b> <b>ราคาขาย</b></td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>ได้งาน → <b>ใบสั่งขาย</b> · ไม่ได้งาน ปิดใบ</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>ใบเสนอราคา (Quotation, QT) เอกสารทางการค้า ไม่ใช่เอกสารภาษี</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — ยังไม่เกิดรายการค้า</td></tr>
</table>

<h3>สร้างใบเสนอราคา</h3>
<ol>
    <li>กด <b>เพิ่ม</b> เลือก <b>ลูกค้า</b> — เงื่อนไขชำระ สกุลเงิน ภาษี และพนักงานขายเติมจากข้อมูลลูกค้า</li>
    <li>ตั้ง <b>ยืนราคาถึง</b> (เริ่มต้น 30 วันจากวันนี้)</li>
    <li>ใส่บรรทัด: เลือกสินค้า ใส่จำนวน — ราคาเติมจาก <b>ราคาขาย</b> หรือราคาสินค้า แก้ราคาและส่วนลด % เองได้</li>
    <li>รายการที่ไม่มีในระบบ (เช่น ค่าขนส่ง ค่าติดตั้ง) พิมพ์รายละเอียดและหน่วยเองได้</li>
    <li>กด <b>บันทึก</b> แล้ว <b>พิมพ์</b> ส่งลูกค้า</li>
</ol>

<h3>ช่องที่ควรรู้</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">ยืนราคาถึง</td><td>ต้องไม่ก่อนวันที่เสนอราคา — เลยวันนี้ไปแล้ว สร้างใบสั่งขายจากใบนี้ไม่ได้ ให้แก้วันหรือทำใบใหม่</td></tr>
    <tr><td class="text-nowrap">อัตราแลกเปลี่ยน</td><td>เติมตามสกุลเงินและวันที่ เงินบาทเป็น 1</td></tr>
    <tr><td class="text-nowrap">สินค้า</td><td>ขายวัตถุดิบ (RM) ตรงไม่ได้ ต้องแปลงเป็นสินค้า FG ที่หน้าสต็อกก่อน</td></tr>
</table>

<h3>สถานะ</h3>
<ul>
    <li><b>รอตอบรับ</b> — แก้ไขได้ กด <b>สร้างใบสั่งขาย</b> เมื่อลูกค้าตกลง หรือ <b>ไม่ได้งาน</b> เมื่อลูกค้าปฏิเสธ</li>
    <li><b>ได้งาน</b> — สร้างใบสั่งขายแล้ว แก้ไม่ได้</li>
    <li><b>ไม่ได้งาน</b> — ปิดใบ แก้ไม่ได้</li>
</ul>
