<table class="table table-sm">
    <tr><td class="text-nowrap">ใบสั่งซื้อต้องสร้างจากใบขอซื้อเท่านั้น</td><td>เปิด = หน้า <b>ใบสั่งซื้อ</b> ไม่มีปุ่มเพิ่ม ต้องเปิดใบขอซื้อก่อน แล้วกด <b>สร้างใบสั่งซื้อ</b> จากใบขอซื้อ เหมาะกับบริษัทที่ต้องการให้ทุกการซื้อมีผู้ขอ · ปิด = สร้างใบสั่งซื้อเองได้เลย</td></tr>
