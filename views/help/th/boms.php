<h3>หน้านี้ใช้ทำอะไร</h3>
<p>กำหนดว่าสินค้าที่ผลิตหนึ่งตัว ใช้ <b>วัตถุดิบ</b> อะไรเท่าไร และผ่าน <b>ขั้นตอน</b> ใดบ้าง พร้อมดูต้นทุนต่อหน่วยโดยประมาณ — ใบสั่งผลิตและ MRP ใช้สูตรนี้คำนวณวัตถุดิบที่ต้องเบิก</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td><b>สินค้าและวัตถุดิบ</b> และ <b>ศูนย์งาน</b> (อัตราค่าแรง ค่าเครื่องจักร โสหุ้ย)</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td><b>ใบสั่งผลิต</b> (วัตถุดิบที่ต้องเบิก) และ <b>วางแผนวัตถุดิบ (MRP)</b> (แตกความต้องการ)</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>สูตรการผลิต (Bill of Materials, BOM) + ขั้นตอนการผลิต (Routing) — ข้อมูลหลักที่ MRP ต้องมี</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — ต้นทุนต่อหน่วยเป็นประมาณการ (วัตถุดิบ + ค่าแรง + โสหุ้ย)</td></tr>
</table>

<h3>ขั้นตอน</h3>
<ol>
    <li>คลิกสินค้าในรายการทางซ้าย (เฉพาะสินค้าที่มีสูตรแล้ว) หรือพิมพ์รหัสในช่อง <b>สินค้าที่ผลิต</b> ด้านบนเพื่อเริ่มสูตรใหม่</li>
    <li>แท็บ <b>วัตถุดิบ</b>: ใส่รหัสวัตถุดิบ จำนวนที่ <b>ใช้ต่อ 1 หน่วย</b> และ <b>เผื่อเสีย %</b> — กด <b>เพิ่มบรรทัด</b> หรือกด Enter ที่ช่องสุดท้ายเพื่อขึ้นแถวใหม่</li>
    <li>แท็บ <b>ขั้นตอน</b>: ใส่เลขขั้นตอน (เช่น 10, 20, 30) ศูนย์งาน งานที่ทำ เวลาตั้งเครื่อง และเวลาต่อชิ้น</li>
    <li>กด <b>บันทึก</b> ครั้งเดียว บันทึกทั้งสองแท็บ</li>
</ol>

<h3>ช่องที่ควรรู้</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">ใช้ต่อ 1 หน่วย</td><td>จำนวนวัตถุดิบต่อสินค้า 1 หน่วย ในหน่วยของวัตถุดิบ เช่น โต๊ะ 1 ตัว ใช้ขาโต๊ะ <code>4</code> ชิ้น</td></tr>
    <tr><td class="text-nowrap">เผื่อเสีย %</td><td>บวกเพิ่มจากจำนวนที่ใช้ เช่น ใช้ 2 กก. เผื่อเสีย 5% = เบิก 2.1 กก. ต่อหน่วย</td></tr>
    <tr><td class="text-nowrap">⋯ (ท้ายแถว)</td><td>เปิดช่อง <b>เริ่มใช้</b> / <b>เลิกใช้</b> และ <b>หมายเหตุ</b> — ใช้เมื่อจะเปลี่ยนวัตถุดิบตามวันที่ ใบสั่งผลิตเลือกเฉพาะแถวที่ใช้ได้ในวันที่เริ่มผลิต ปล่อยว่าง = ใช้ตลอด</td></tr>
    <tr><td class="text-nowrap">ตั้งเครื่อง (ชม.)</td><td>เวลาเตรียมเครื่องต่อครั้ง ไม่นำมาคิดในต้นทุนต่อหน่วยของหน้านี้</td></tr>
    <tr><td class="text-nowrap">เวลาต่อชิ้น (ชม.)</td><td>ชั่วโมงที่ใช้ต่อ 1 หน่วย เช่น 15 นาที = <code>0.25</code></td></tr>
</table>

<h3>ต้นทุน/หน่วย คิดอย่างไร</h3>
<ul>
    <li><b>วัตถุดิบ</b> = ใช้ต่อ 1 หน่วย × (1 + เผื่อเสีย %) × ต้นทุนปัจจุบันของวัตถุดิบ</li>
    <li><b>ขั้นตอน</b> = เวลาต่อชิ้น × (ค่าแรง + ค่าเครื่องจักร + ค่าโสหุ้ย ต่อชั่วโมง) ของศูนย์งาน</li>
    <li><b>ต้นทุนรวม/หน่วย</b> ด้านขวาของแท็บ = วัตถุดิบ + ขั้นตอน — เป็นตัวเลขประมาณการ ต้นทุนจริงมาจากใบสั่งผลิต</li>
</ul>

<h3>หมายเหตุ</h3>
<ul>
    <li>ใส่วัตถุดิบที่ทำให้สูตรวนกลับมาที่ตัวเองไม่ได้ (เช่น A ใช้ B แล้ว B ใช้ A)</li>
    <li>ลบทุกแถวในแท็บแล้วบันทึก = ลบส่วนนั้นของสูตร ปุ่ม <b>ลบ</b> ด้านบนลบทั้งวัตถุดิบและขั้นตอนของสินค้านี้</li>
    <li>แก้สูตรแล้วไม่กระทบใบสั่งผลิตที่เริ่มผลิตไปแล้ว</li>
</ul>
