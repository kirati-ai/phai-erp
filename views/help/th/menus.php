<h3>หน้านี้คืออะไร</h3>
<p>รายการเมนูด้านซ้ายทั้งหมด ใช้เปลี่ยนชื่อเมนู เรียงลำดับใหม่ เปลี่ยนไอคอน หรือเพิ่มลิงก์ของตัวเอง (เช่น ลิงก์ไปเว็บที่ใช้บ่อย) — เมนูที่ติดตั้งมาใช้ได้เลย ไม่จำเป็นต้องแก้</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>ติดตั้งมาเรียง ข้อมูลหลัก → จัดซื้อ → คลังสินค้า → ผลิต → ขาย → บัญชี → ตั้งค่าระบบ</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>เมนูซ้ายของทุกคน แสดงเฉพาะที่บทบาทมีสิทธิ์</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>เมนูระบบ (Menu) — ลำดับเมนูเรียงตามสายงานของ ERP</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี</td></tr>
</table>

<h3>ช่องต่าง ๆ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">กลุ่ม</td><td>เลขหมวดเมนู เช่น <code>1</code> ข้อมูลหลัก, <code>9</code> ตั้งค่าระบบ</td></tr>
    <tr><td class="text-nowrap">รหัส</td><td>รหัสของแถว เช่น <code>1.11</code> — แถวที่ลงท้าย <code>.0</code> คือหัวหมวด (ชื่อและไอคอนของหมวด)</td></tr>
    <tr><td class="text-nowrap">ชื่อเมนู</td><td>ข้อความที่แสดงในเมนู</td></tr>
    <tr><td class="text-nowrap">ลิงก์</td><td>หน้าที่จะเปิด เช่น <code>/parts</code> หรือ <code>/parts?type=RM</code> (เปิดโดยกรองไว้) — ใส่ <code>#</code> = หัวข้อย่อยในหมวด เช่น "ตั้งค่า" "ทำรายการ"</td></tr>
    <tr><td class="text-nowrap">รหัสโปรแกรมที่ต้องมีสิทธิ์</td><td>เมนูแสดงเฉพาะผู้ที่มีสิทธิ์ <b>ดู</b> หน้านี้ เช่น <code>parts</code> — <code>*</code> = ทุกคนเห็น</td></tr>
    <tr><td class="text-nowrap">ไอคอน</td><td>ชื่อไอคอน Tabler เช่น <code>ti ti-package</code></td></tr>
    <tr><td class="text-nowrap">ลำดับ</td><td>ตัวเลขน้อยอยู่บน — ลำดับของหัวหมวด (<code>.0</code>) ใช้เรียงหมวด</td></tr>
    <tr><td class="text-nowrap">เปิดที่</td><td><b>หน้าเดิม</b> หรือ <b>แท็บใหม่</b> (เหมาะกับลิงก์เว็บภายนอก)</td></tr>
</table>

<h3>ย้ายเมนูขึ้นลง</h3>
<ol>
    <li>คลิกแถวเมนูที่ต้องการ แล้วกดแก้ไข</li>
    <li>เปลี่ยน <b>ลำดับ</b> ให้อยู่ระหว่างเลขของสองเมนูที่ต้องการ ถ้าเลขชนกัน ให้เลื่อนเลขของเมนูถัดไปด้วย</li>
    <li>กด <b>บันทึก</b> แล้วรีเฟรชหน้า เมนูซ้ายจะเปลี่ยนตาม</li>
</ol>
<p class="text-secondary">ลบแถวเมนูไม่ได้ลบหน้าจอหรือสิทธิ์ แค่ไม่มีทางเข้าจากเมนู — อย่าลบเมนู "ภาพรวมจัดซื้อ" (<code>/purchase</code>) เพราะระบบจะคืนเมนูทั้งหมดเป็นค่าเริ่มต้น</p>
