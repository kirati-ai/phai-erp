<h3>ขั้นตอน</h3>
<ol>
    <li>กด <b>จ่ายชำระ</b> บนใบสำคัญจ่าย (เติมผู้ขายและยอดให้) หรือกด <b>เพิ่ม</b> แล้วเลือกผู้ขาย</li>
    <li>เลือกวันที่ และ <b>บัญชีรับ/จ่ายเงิน</b> (เงินสดหรือบัญชีธนาคารที่จ่ายออก)</li>
    <li>ในตาราง ใส่ยอด <b>จ่าย</b> ของแต่ละใบสำคัญจ่าย ปุ่มลูกศรข้างเลขที่ใส่ <b>เต็มยอด</b> ให้ — จ่ายบางส่วนได้ ไม่เกินยอดคงเหลือ</li>
    <li>ถ้าต้องหักภาษี เลือก <b>แบบ</b> ภ.ง.ด.53 (นิติบุคคล) หรือ ภ.ง.ด.3 (บุคคลธรรมดา) แล้วกรอกตารางหัก ณ ที่จ่ายใต้รายการ (ดูหัวข้อถัดไป)</li>
    <li>ตรวจ <b>จ่ายสุทธิ</b> ให้ตรงกับเงินที่โอนจริง แล้ว <b>บันทึก</b></li>
</ol>

<h3>ตารางหัก ณ ที่จ่าย (หลายอัตราได้)</h3>
<p>ถ้าบรรทัดของตั้งหนี้ระบุรหัสหัก ณ ที่จ่ายไว้ ตารางนี้เติมเองตามยอดที่จ่าย (รวมยอดก่อน VAT ตามรหัส) — แก้ตารางเองเมื่อไร ระบบหยุดเติมให้</p>
<table class="table table-sm">
    <tr><td class="text-nowrap">หัก ณ ที่จ่าย</td><td>รหัสจาก <b>รหัสภาษีหัก ณ ที่จ่าย</b> เช่น WHT3 ค่าบริการ 3%</td></tr>
    <tr><td class="text-nowrap">ยอดก่อนหัก</td><td>อัตราแรกระบบเติมจากยอดก่อน VAT ของที่จ่ายให้ แก้ได้</td></tr>
    <tr><td class="text-nowrap">อัตรา % / ภาษีหัก ณ ที่จ่าย</td><td>คำนวณให้ = ยอดก่อนหัก × อัตรา</td></tr>
</table>
<p>ใบเดียวมีหลายประเภทเงินได้ เช่น ค่าบริการ 3% กับค่าขนส่ง 1%: กด <b>เพิ่มอัตรา</b> แล้วแบ่งยอดก่อนหัก (แถวใหม่เริ่มจากยอดที่เหลือ) — ยอดก่อนหักรวมกันต้องไม่เกินยอดจ่าย และใช้รหัสซ้ำไม่ได้ ทุกอัตราอยู่ใน 50 ทวิ ใบเดียว และเป็นบรรทัดแยกในรายงาน ภ.ง.ด.</p>
<p class="text-secondary">ตัวอย่าง: จ่ายค่าบริการติดตั้ง 10,700 (ก่อน VAT 10,000) หัก 3% = 300 จ่ายสุทธิ 10,400</p>

<h3>ลงบัญชีอย่างไร</h3>
<p>เดบิต เจ้าหนี้ตามใบสำคัญจ่าย (ยอดจ่าย) / เครดิต บัญชีธนาคาร (จ่ายสุทธิ) / เครดิต บัญชีภาษีหัก ณ ที่จ่ายค้างจ่ายของแต่ละรหัส</p>
<p>หลังบันทึก มีปุ่ม <b>50 ทวิ</b> (พิมพ์หนังสือรับรอง) และ <b>พิมพ์ / PDF</b> (ใบจ่ายชำระ — หลักฐานการจ่ายเงินจริง ต่างจากใบสำคัญจ่ายที่เป็นใบอนุมัติก่อนจ่าย)</p>

<h3>การยกเลิก</h3>
<p><b>ยกเลิกเอกสาร</b> แล้วใบสำคัญจ่ายกลับเป็นรอจ่าย หนังสือรับรอง 50 ทวิ ถูกยกเลิก และกลับรายการบัญชีด้วยวันที่วันนี้ — สถานะ <b>ลงบัญชีแล้ว</b> → <b>ยกเลิก</b></p>

<p class="text-secondary">จ่าย/รับเป็น<b>เงินสด</b>: เลือกบัญชี <b>CASH เงินสดย่อย (ของผู้ทำรายการ)</b> — เงินออกจาก/เข้ากล่องเงินสดย่อยของคนที่ทำเอกสารนี้ (ดูหน้า เงินสดย่อย) ยกเลิกเอกสารได้เมื่อเดือนนั้นของกล่องยังไม่นับ</p>

<h3>เอกสารแนบ</h3>
<p>หัวข้อ <b>เอกสารแนบ</b> ใต้เอกสารที่บันทึกแล้ว: กด <b>แนบไฟล์</b> แนบรูปหรือ PDF ได้หลายไฟล์ เช่น สลิปโอนเงิน สำเนาเช็ค ใบเสร็จรับเงินของผู้ขาย — คลิกเพื่อเปิด กด × เพื่อลบ — กดรูปคลิปท้ายแถวในหน้ารายการ เปิดหน้าต่างเอกสารแนบของแถวนั้นได้เลยโดยไม่ต้องเปิดเอกสาร (คลิปสีเขียวพร้อมตัวเลข = จำนวนไฟล์ที่แนบไว้)</p>
<p class="text-secondary">แนบต้องมีสิทธิ์เพิ่มหรือแก้ไขของหน้านี้ ลบต้องมีสิทธิ์แก้ไขหรือลบ แนบได้ทุกสถานะ</p>
