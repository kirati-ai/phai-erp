<h3>หน้านี้คืออะไร</h3>
<p>บันทึก <b>การจ่ายเงินจริง (PV)</b> ให้ผู้ขาย ตาม <b>ใบสำคัญจ่าย</b> ที่รอจ่าย จ่ายหลายใบในครั้งเดียวได้ และหักภาษี ณ ที่จ่ายได้ — ระบบออก <b>หนังสือรับรองหัก ณ ที่จ่าย (50 ทวิ)</b> ให้เอง</p>
<p><b>ใบสำคัญจ่ายรอจ่ายชำระ</b> เหนือรายการแสดงใบสำคัญจ่ายที่ยังจ่ายไม่ครบ เรียงตามวันนัดจ่าย (ตัวแดง = เลยวันนัดจ่าย, ซ่อนเมื่อไม่มี) กด <b>จ่ายชำระ</b> ระบบเปิดใบจ่ายเงินใหม่พร้อมผู้ขายและยอดเต็มของใบนั้น</p>

