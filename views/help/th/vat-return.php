<h3>ใช้งาน</h3>
<ol>
    <li>เลือก <b>เดือนภาษี</b> (เริ่มต้นเป็นเดือนที่แล้ว) ตรวจตัวเลขกับรายงานภาษีขายและภาษีซื้อ</li>
    <li>กด <b>พิมพ์ / PDF</b> ได้ใบสรุปสำหรับกรอกแบบ</li>
    <li>กด <b>ยื่นและลงบัญชี</b> — ตัวเลขของเดือนนั้นถูกเก็บไว้ (แก้เอกสารย้อนหลังภายหลังไม่เปลี่ยนตัวเลขที่ยื่นแล้ว) ยื่นได้เฉพาะเดือนที่สิ้นสุดแล้ว และต้องยื่นเรียงเดือน</li>
    <li>ยื่นผิด กด <b>ยกเลิกการยื่น</b> ได้เฉพาะเดือนล่าสุด ระบบกลับรายการบัญชีด้วยวันที่วันนี้</li>
</ol>
<p class="text-secondary">ลงบัญชีวันที่สิ้นเดือนภาษี ถ้างวดนั้นปิดแล้วใช้วันแรกของงวดที่เปิด</p>

<h3>เอกสารแนบ</h3>
<p>กดรูปคลิปในแถวของเดือนในตาราง <b>ยื่นแล้ว</b> เปิดหน้าต่าง <b>เอกสารแนบ</b> ของเดือนนั้น (คลิปสีเขียวพร้อมตัวเลข = จำนวนไฟล์): กด <b>แนบไฟล์</b> แนบรูปหรือ PDF ได้หลายไฟล์ เช่น แบบ ภ.พ.30 ที่ยื่นแล้ว ใบเสร็จชำระภาษี — คลิกเพื่อเปิด กด × เพื่อลบ</p>
<p class="text-secondary">แนบต้องมีสิทธิ์เพิ่มหรือแก้ไขของหน้านี้ ลบต้องมีสิทธิ์แก้ไขหรือลบ แนบได้ทุกสถานะ ยกเลิกการยื่นแล้วไฟล์แนบของเดือนนั้นถูกลบด้วย</p>
