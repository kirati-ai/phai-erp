<h3>บันทึกรายการเอง</h3>
<ol>
    <li>กด <b>เพิ่ม</b> ใส่วันที่ (ต้องไม่ก่อนงวดที่เปิด) และคำอธิบาย</li>
    <li>แต่ละบรรทัดเลือกบัญชี ศูนย์ต้นทุน (ถ้ามี) และใส่ <b>เดบิต</b> หรือ <b>เครดิต</b> อย่างใดอย่างหนึ่ง กด <b>เพิ่มบรรทัด</b> ตามต้องการ (อย่างน้อย 2 บรรทัด)</li>
    <li>ช่อง <b>ผลต่าง</b> ต้องเป็น 0 (เดบิตเท่ากับเครดิต) จึง <b>บันทึก</b> ได้</li>
</ol>
<p class="text-secondary">ตัวอย่างยอดยกมาเงินฝาก: เดบิต <code>10201</code> เงินฝากออมทรัพย์ 500,000 / เครดิต <code>30101</code> ทุนเรือนหุ้น 500,000</p>
<p><b>บัญชีคุม</b> (ลูกหนี้การค้า เจ้าหนี้การค้า สินค้า) ไม่มีให้เลือก — ต้องลงผ่านเอกสาร เช่น ใบแจ้งหนี้ ตั้งหนี้ ตรวจนับสต็อก เพื่อให้ยอดรายตัวตรงกับบัญชี</p>

<h3>แก้ไขรายการ</h3>
<p>รายการที่บันทึกแล้วแก้ไม่ได้ เปิดรายการสมุดรายวันทั่วไปแล้วกด <b>กลับรายการ</b> ระบบสร้างรายการใหม่กลับข้างทุกบรรทัดลงวันที่วันนี้ แล้วบันทึกรายการที่ถูกต้องใหม่ — รายการจากเอกสารอื่นให้ยกเลิกที่เอกสารต้นทาง</p>
<p>เปิดรายการใดก็ได้เพื่อดูบรรทัดเดบิต/เครดิต และ <b>พิมพ์</b> ได้</p>

<h3>เอกสารแนบ</h3>
<p>หัวข้อ <b>เอกสารแนบ</b> ใต้เอกสารที่บันทึกแล้ว: กด <b>แนบไฟล์</b> แนบรูปหรือ PDF ได้หลายไฟล์ เช่น เอกสารประกอบรายการ (สัญญา ใบแจ้งหนี้ บันทึกคำนวณ) — คลิกเพื่อเปิด กด × เพื่อลบ — กดรูปคลิปท้ายแถวในหน้ารายการ เปิดหน้าต่างเอกสารแนบของแถวนั้นได้เลยโดยไม่ต้องเปิดเอกสาร (คลิปสีเขียวพร้อมตัวเลข = จำนวนไฟล์ที่แนบไว้)</p>
<p class="text-secondary">แนบต้องมีสิทธิ์เพิ่มหรือแก้ไขของหน้านี้ ลบต้องมีสิทธิ์แก้ไขหรือลบ แนบได้ทุกสถานะ</p>
