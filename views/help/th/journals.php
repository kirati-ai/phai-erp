<h3>หน้านี้คืออะไร</h3>
<p>รายการบัญชี <b>ทั้งหมด</b> ของบริษัท หนึ่งแถว = หนึ่งรายการ (ประเภท + อ้างอิง + วันที่) ทั้งที่เอกสารลงให้อัตโนมัติ และที่บันทึกเองเป็น <b>สมุดรายวันทั่วไป</b> (JE) เช่น ยอดยกมา ค่าใช้จ่ายค้างจ่าย นำส่งภาษี</p>
<p>เมนู <b>สมุดรายวันขาย</b> คือหน้านี้ที่กรองประเภท <b>ขาย</b> ไว้ (รายการจากใบแจ้งหนี้)</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>ทุกเอกสารที่ลงบัญชี (รับสินค้า ตั้งหนี้ ขาย รับ/จ่ายเงิน ผลิต สินทรัพย์) และรายการที่บันทึกเอง</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td><b>งบทดลอง</b> → ปิดงวด</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>สมุดรายวันทั่วไป (General Journal, JE) — ใบสำคัญทั่วไปสำหรับรายการที่ไม่มีเอกสารต้นทาง</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>JE: Dr / Cr ตามที่บันทึก ต้องสมดุล (ใช้บัญชีคุมไม่ได้)</td></tr>
</table>

