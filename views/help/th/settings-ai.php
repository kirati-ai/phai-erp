<h3>หน้านี้ใช้ทำอะไร</h3>
<p>เปิดใช้เมนู <b>ถาม AI</b> ให้ผู้ใช้ถามข้อมูลในระบบเป็นภาษาคนได้ เช่น "ใบสั่งซื้อที่ยังไม่ได้รับของ" และดูค่าใช้จ่าย AI ของแต่ละคน</p>
<p>AI อ่านข้อมูลได้อย่างเดียว ไม่สร้างหรือแก้ไขอะไร และเห็นเฉพาะข้อมูลที่ผู้ถามมีสิทธิ์ดูตาม <b>บทบาทและสิทธิ์</b></p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>API อ่านข้อมูลของหน้าจอต่าง ๆ และ <b>บทบาทและสิทธิ์</b> ของผู้ถาม</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>เมนู <b>ถาม AI</b></td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>ผู้ช่วย AI (AI Assistant) ส่วนเสริม ไม่ใช่โมดูลหลักของ ERP</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — AI อ่านได้อย่างเดียว</td></tr>
</table>

<h3>ช่องต่าง ๆ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">ผู้ให้บริการ</td><td><b>Claude (Anthropic)</b> หรือ <b>Gemini (Google)</b> — ต้องสมัครและจ่ายค่าใช้งานกับผู้ให้บริการเอง</td></tr>
    <tr><td class="text-nowrap">รุ่นโมเดล</td><td>เว้นว่างได้ ระบบใช้รุ่นที่แสดงจาง ๆ ในช่อง ใส่เองถ้าต้องการรุ่นอื่นตามชื่อในเว็บผู้ให้บริการ</td></tr>
    <tr><td class="text-nowrap">API key</td><td>รหัสที่สร้างจากเว็บผู้ให้บริการ: Claude ที่ <code>console.anthropic.com</code> → API Keys, Gemini ที่ <code>aistudio.google.com</code> → Get API key — บันทึกแล้วจะไม่แสดงกลับ เว้นว่างเพื่อใช้ค่าเดิม</td></tr>
    <tr><td class="text-nowrap">ราคาขาเข้า / ขาออก</td><td>ราคาเป็นดอลลาร์ต่อ 1 ล้านโทเค็นของรุ่นที่ใช้ ดูจากหน้าราคาของผู้ให้บริการ — ใช้คำนวณตาราง <b>การใช้งาน</b> เท่านั้น ไม่มีผลกับยอดที่ถูกเรียกเก็บจริง</td></tr>
</table>

<h3>เปิดใช้ AI</h3>
<ol>
    <li>สร้าง API key ที่เว็บผู้ให้บริการ (ตั้งวงเงินใช้จ่ายรายเดือนที่นั่นด้วยจะปลอดภัยกว่า)</li>
    <li>เลือกผู้ให้บริการ วาง API key ใส่ราคา</li>
    <li>เปิดสวิตช์ <b>เปิดใช้ AI</b> แล้วกด <b>บันทึก</b></li>
    <li>ให้สิทธิ์ <b>ดู</b> หน้า "ถาม AI" กับบทบาทที่จะใช้ ใน <b>บทบาทและสิทธิ์</b> (ADMIN ใช้ได้เลย)</li>
    <li>เมนู <b>ถาม AI</b> จะขึ้นใต้หน้าแรกในเมนูซ้าย ลองถามดู</li>
</ol>

<h3>ตารางการใช้งาน</h3>
<p>จำนวนคำถาม โทเค็น และค่าใช้จ่ายโดยประมาณ (ดอลลาร์) ของแต่ละผู้ใช้ เดือนนี้และทั้งหมด ใช้ดูว่าใครใช้มากน้อยแค่ไหน</p>
<p class="text-secondary">ค่าทั้งหมดเก็บในไฟล์ config.php บนเครื่องเซิร์ฟเวอร์ ไม่อยู่ในฐานข้อมูล — ถ้าขึ้นข้อความว่าเขียนไฟล์ไม่ได้ ให้ผู้ดูแลเครื่องเปิดสิทธิ์เขียนไฟล์ config.php</p>
