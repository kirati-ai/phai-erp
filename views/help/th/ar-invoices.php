<h3>ขั้นตอน</h3>
<ol>
    <li>กด <b>เพิ่ม</b> เลือกชนิด ลูกค้า และวันที่ (ใบลดหนี้/เพิ่มหนี้ เลือกใบที่อ้างถึงและเหตุผล)</li>
    <li>ใส่บรรทัด: เลือกสินค้าหรือพิมพ์รายการเอง จำนวน ราคา — ใบลดหนี้ใส่ <b>จำนวนติดลบ</b> (เช่น -1) ราคาเป็นบวก ยอดทั้งใบจึงติดลบ — ใบวางบิล รับชำระ และรายงานภาษีขายหักออกให้เอง</li>
    <li><b>บันทึก</b> แล้ว <b>พิมพ์</b> หรือ <b>ส่ง e-Tax</b> / <b>XML e-Tax</b> (มีเมื่อตั้งค่า e-Tax แล้ว)</li>
</ol>

