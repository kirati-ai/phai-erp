</table>

<h3>โอนย้าย</h3>
<p>ย้ายของไปคลังหรือตำแหน่งอื่น ล็อตและวันหมดอายุตามไปด้วย มูลค่าที่ย้าย = จำนวน × ต้นทุน/หน่วยของแถวนี้</p>
<ol>
    <li>กด <b>โอนย้าย</b> ใส่วันที่ (ไม่เกินวันนี้) และจำนวน</li>
    <li>เลือก <b>ไปคลัง</b> และ <b>ไปตำแหน่ง</b> (ต้องไม่ใช่ที่เดิม) แล้วกด <b>บันทึก</b></li>
</ol>
<p>ได้เลขที่เอกสาร TO ในประวัติเป็น "โอนออก" และ "โอนเข้า" คู่กัน</p>

<h3>แปลงเป็น FG (เฉพาะวัตถุดิบ)</h3>
<p>วัตถุดิบขายตรงไม่ได้ ต้องแปลงเป็นสินค้า FG ก่อน เช่น ไม้แผ่น 10 แผ่น → ชั้นวาง 2 ตัว</p>
<ol>
    <li>กด <b>แปลงเป็น FG</b> ใส่ <b>จำนวน</b> วัตถุดิบที่ใช้ เลือก <b>เป็นสินค้า FG</b> ใส่ <b>จำนวน FG</b> และ <b>ไปตำแหน่ง</b> (ในคลังเดียวกัน)</li>
    <li>กด <b>บันทึก</b> วัตถุดิบออกที่ต้นทุน สินค้า FG เข้าด้วยมูลค่าเดียวกัน ล็อตของ FG = เลขที่เอกสาร</li>
</ol>

