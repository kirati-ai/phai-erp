<h3>หน้านี้คืออะไร</h3>
<p>สต็อกหนึ่งแถว = สินค้าหนึ่งตัว ใน คลัง + ตำแหน่ง + ล็อต เดียว แท็บ <b>รายละเอียด</b> แสดงคงเหลือ จองแล้ว ต้นทุน/หน่วย มูลค่า ล็อตผู้ขาย วันหมดอายุ แท็บ <b>ประวัติความเคลื่อนไหว</b> แสดงทุกรายการเข้าออกของแถวนี้</p>

