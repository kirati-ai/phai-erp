<h3>หน้านี้ใช้ทำอะไร</h3>
<p><b>ใบขอซื้อ</b> คือคำขอจากพนักงานหรือแผนกว่าต้องการของอะไร เท่าไร เมื่อไร ฝ่ายจัดซื้อแปลงเป็น <b>ใบสั่งซื้อ</b> ด้วยปุ่มเดียว — ไม่มีขั้นอนุมัติในระบบ ถ้าต้องให้หัวหน้าเซ็น ให้กด <b>พิมพ์</b> ไปเซ็น</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>ผู้ขอ (พนักงาน แผนก) หรือ <b>วางแผนวัตถุดิบ (MRP)</b> ที่สร้างใบขอซื้อให้</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td><b>ใบสั่งซื้อ</b> (ปุ่ม สร้างใบสั่งซื้อ)</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>ใบขอซื้อ (Purchase Requisition, PR) — เอกสารภายใน ไม่มีแบบตามกฎหมาย</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — ยังไม่มีการซื้อหรือหนี้เกิดขึ้น</td></tr>
</table>

<h3>ช่องที่ควรรู้</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">ผู้ขอ / แผนก</td><td>คนที่ต้องการของ เช่น "สมชาย ใจดี" แผนก "ผลิต"</td></tr>
    <tr><td class="text-nowrap">สินค้า</td><td>เลือกจากรายการ หรือพิมพ์เองถ้าไม่มีในระบบ (เช่น ค่าซ่อมแอร์) แล้วใส่รายละเอียดและหน่วยเอง</td></tr>
    <tr><td class="text-nowrap">ต้องการใช้</td><td>วันที่ต้องได้ของ ค่าเริ่มต้นอีก 7 วัน</td></tr>
    <tr><td class="text-nowrap">ราคาประมาณ</td><td>ระบบเติมราคาซื้อครั้งล่าสุดให้ ใช้เป็นราคาตั้งต้นในใบสั่งซื้อ</td></tr>
    <tr><td class="text-nowrap">ผู้ขายที่แนะนำ</td><td>ร้านที่ควรสั่ง ถ้าใส่ ใบสั่งซื้อจะแยกไปตามผู้ขายของแต่ละบรรทัด</td></tr>
    <tr><td class="text-nowrap">ใบสั่งซื้อ</td><td>เลขใบสั่งซื้อที่สร้างจากบรรทัดนั้น คลิกเปิดได้</td></tr>
</table>

<h3>ขอซื้อแล้วสั่งซื้อ</h3>
<ol>
    <li>กด <b>เพิ่ม</b> ใส่ผู้ขอ แผนก แล้วเพิ่มบรรทัดสินค้า จำนวน วันที่ต้องการใช้ กด <b>บันทึก</b></li>
    <li>ฝ่ายจัดซื้อเปิดใบขอซื้อ กด <b>สร้างใบสั่งซื้อ</b></li>
    <li>ถ้ามีบรรทัดที่ไม่ได้ระบุผู้ขาย ระบบถาม "ผู้ขายสำหรับบรรทัดที่ไม่ได้ระบุผู้ขาย" — เลือกแล้วยืนยัน</li>
    <li>ได้ใบสั่งซื้อแยกตามผู้ขาย (ผู้ขายละหนึ่งใบ) ระบบเปิดใบแรกให้ ตรวจราคาแล้วบันทึก</li>
</ol>

<h3>สถานะ</h3>
<ul>
    <li><b>เปิด</b> — แก้ไขได้ สร้างใบสั่งซื้อหรือยกเลิกได้</li>
    <li><b>สั่งซื้อแล้ว</b> — สร้างใบสั่งซื้อแล้ว แก้ไม่ได้ ถ้ายกเลิกใบสั่งซื้อที่สร้างจากใบนี้ ใบขอซื้อกลับเป็น เปิด อีกครั้ง</li>
    <li><b>ยกเลิก</b> — กด <b>ยกเลิกเอกสาร</b> ได้เฉพาะตอนเปิด เลขที่ยังอยู่ในระบบ</li>
</ul>
<p class="text-secondary">ใบขอซื้อสร้างจากหน้า <b>วางแผนวัตถุดิบ (MRP)</b> ได้ด้วย — เหนือรายการมีกล่อง <b>MRP แนะนำให้ซื้อ</b> (แสดงเมื่อมีรายการ แถวสีแดง = เลยวันที่ควรสั่ง; มาจากการรัน MRP ครั้งล่าสุด) กด <b>สร้างใบขอซื้อ</b> ในแถว หรือติ๊กหลายแถวแล้วกด <b>สร้างใบขอซื้อจากที่เลือก</b> ได้ใบขอซื้อใบเดียว</p>

<h3>เอกสารแนบ</h3>
<p>หัวข้อ <b>เอกสารแนบ</b> ใต้เอกสารที่บันทึกแล้ว: กด <b>แนบไฟล์</b> แนบรูปหรือ PDF ได้หลายไฟล์ เช่น ใบเสนอราคาของผู้ขาย (หลายเจ้าไว้เทียบ) สเปก รูปตัวอย่าง — คลิกเพื่อเปิด กด × เพื่อลบ — กดรูปคลิปท้ายแถวในหน้ารายการ เปิดหน้าต่างเอกสารแนบของแถวนั้นได้เลยโดยไม่ต้องเปิดเอกสาร (คลิปสีเขียวพร้อมตัวเลข = จำนวนไฟล์ที่แนบไว้)</p>
<p class="text-secondary">แนบต้องมีสิทธิ์เพิ่มหรือแก้ไขของหน้านี้ ลบต้องมีสิทธิ์แก้ไขหรือลบ แนบได้ทุกสถานะ</p>
