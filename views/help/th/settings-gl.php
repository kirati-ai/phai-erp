<h3>หน้านี้คืออะไร</h3>
<p><b>บัญชีตั้งต้น</b> ที่ระบบใช้ลงบัญชีอัตโนมัติจากเอกสาร (รับสินค้า ตั้งหนี้ ใบแจ้งหนี้ รับ/จ่ายเงิน ผลิต) และงวดบัญชีที่เปิดอยู่ ค่าที่ติดตั้งมาใช้ได้เลย แก้เมื่อผังบัญชีของบริษัทต่างไป</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>ตั้งครั้งแรกตอนเริ่มใช้ระบบ จาก <b>ผังบัญชี</b></td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>ทุกเอกสารที่ลงบัญชีอัตโนมัติ (เมื่อสายผลิตภัณฑ์หรือคู่ค้าไม่ได้กำหนดบัญชีเอง)</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>ค่าตั้งบัญชี (ตาราง <code>gl_ctrl</code>) — บัญชีตั้งต้นและงวดที่เปิด</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — บอกว่าเอกสารลงบัญชีใด</td></tr>
</table>

