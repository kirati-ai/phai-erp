    <tr><td class="text-nowrap">สกุลเงินหลัก</td><td>ปกติ THB — ลูกหนี้ เจ้าหนี้ และบัญชีเป็นสกุลนี้</td></tr>
    <tr><td class="text-nowrap">บัญชีกำไรสะสม</td><td>กำไรขาดทุนของปีก่อน ๆ แสดงรวมในบัญชีนี้ในงบทดลอง</td></tr>
</table>

