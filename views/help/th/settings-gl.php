<h3>เลขที่เอกสาร</h3>
<p>ตารางท้ายหน้ากำหนดคำนำหน้า รูปแบบ และเลขถัดไปของเอกสารในหมวดนี้ (ใบเสร็จรับเงิน ใบรับมัดจำ ตั้งหนี้ ใบสำคัญจ่าย หนังสือรับรองหัก ณ ที่จ่าย ใบจ่ายชำระ สมุดรายวันทั่วไป) แล้วกด <b>บันทึก</b> ของตาราง — มีผลกับเอกสารใหม่เท่านั้น ดูรายละเอียดรูปแบบใน ตั้งค่าระบบ → <b>ตั้งค่าเลขที่เอกสาร</b> ซึ่งรวมทุกหมวดไว้ที่เดียว</p>
