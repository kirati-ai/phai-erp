<ol>
    <li>กด <b>เพิ่ม</b> ใส่รหัส ชื่อ หน่วยนับ และเลือกสายผลิตภัณฑ์</li>
    <li>เลือกที่มา (ซื้อมา / ผลิตเอง) ใส่ราคาขายในแท็บ <b>ราคาและต้นทุน</b> ถ้าขาย</li>
    <li>กด <b>บันทึก</b> — ยอดคงเหลือเริ่มต้นใส่ผ่าน <b>คลังสินค้า › ตรวจนับสต็อก</b> ไม่ใช่หน้านี้</li>
</ol>
<p class="text-secondary">มีสินค้าหลายตัว ใช้ไอคอน <b>นำเข้าจาก Excel</b> กด <b>ไฟล์ตัวอย่าง</b> กรอกแล้วนำเข้า — รหัสที่มีอยู่แล้วจะถูกแก้ รหัสใหม่จะถูกเพิ่ม ผิดแถวเดียวไม่บันทึกทั้งไฟล์</p>
<p class="text-secondary">สินค้าที่มีสต็อก ประวัติความเคลื่อนไหว เอกสาร สูตรการผลิต หรือราคาขายแล้ว ลบไม่ได้ ระบบจะแจ้ง "ลบไม่ได้ ข้อมูลนี้ถูกใช้งานอยู่" — ให้เปลี่ยนสถานะเป็น เลิกใช้ แทน</p>

<h3>เอกสารแนบ</h3>
<p>หัวข้อ <b>เอกสารแนบ</b> ท้ายหน้าต่างข้อมูลของรายการที่บันทึกแล้ว: กด <b>แนบไฟล์</b> แนบรูปหรือ PDF ได้หลายไฟล์ เช่น สเปก แบบ (drawing) รูปสินค้า เอกสารความปลอดภัยสารเคมี (MSDS) — คลิกเพื่อเปิด กด × เพื่อลบ — กดรูปคลิปท้ายแถวในหน้ารายการ เปิดหน้าต่างเอกสารแนบของแถวนั้นได้เลยโดยไม่ต้องเปิดเอกสาร (คลิปสีเขียวพร้อมตัวเลข = จำนวนไฟล์ที่แนบไว้)</p>
<p class="text-secondary">แนบต้องมีสิทธิ์เพิ่มหรือแก้ไขของหน้านี้ ลบต้องมีสิทธิ์แก้ไขหรือลบ แนบได้ทุกสถานะ ลบสินค้าแล้วไฟล์แนบถูกลบด้วย</p>
