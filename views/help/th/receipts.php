<h3>หน้านี้ใช้ทำอะไร</h3>
<p>บันทึกของที่ผู้ขายส่งมาตาม <b>ใบสั่งซื้อ</b> ระบบเพิ่มสต็อก คิดต้นทุนถัวเฉลี่ย และลงบัญชีให้เอง (สินค้า / สินค้ารับแล้วรอใบแจ้งหนี้) รับบางส่วนได้ ที่เหลือรอรับครั้งหน้า</p>

