<h3>รับของ</h3>
<ol>
    <li>กด <b>รับสินค้า</b> ที่ใบสั่งซื้อในกล่อง <b>ใบสั่งซื้อรอรับสินค้า</b> เหนือรายการ (แถวสีแดง = เลยกำหนดส่ง) ได้หน้ารับที่เลือกใบนั้นไว้ให้ — หรือกด <b>เพิ่ม</b> แล้วเลือกใบสั่งซื้อเอง</li>
    <li>เลือกคลัง ใส่ <b>เลขที่ใบกำกับภาษี / ใบส่งของ</b> (ช่องเดียว ใส่เลขของเอกสารที่มากับของ) และวันที่ในเอกสาร</li>
    <li>ใส่จำนวนใน "รับครั้งนี้" หรือกด <b>รับครบทุกรายการ</b> ถ้าได้ครบตามที่ค้าง</li>
    <li>ตรวจตำแหน่งและล็อต แล้วกด <b>บันทึก</b> — รับครบทุกบรรทัดแล้วใบสั่งซื้อปิดเอง</li>
</ol>

<h3>หลังบันทึก</h3>
<ul>
    <li>ใบรับเป็นหน้าดูอย่างเดียว <b>แก้และยกเลิกไม่ได้</b> เพราะสต็อกและบัญชีลงไปแล้ว</li>
    <li>ป้าย <b>รอตั้งหนี้</b> / <b>ตั้งหนี้แล้ว</b> — กดปุ่ม <b>ตั้งหนี้</b> เพื่อตั้งเจ้าหนี้จากใบรับนี้ (หรือติ๊กหลายใบที่คิว <b>รอตั้งหนี้</b> บนหน้า บัญชี → <b>ตั้งหนี้เจ้าหนี้</b>)</li>
    <li>ค่าขนส่งหรืออากรของล็อตนี้ ใส่ที่ <b>ค่าใช้จ่ายนำเข้า</b></li>
</ul>

