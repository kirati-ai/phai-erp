<h3>หน้านี้ใช้ทำอะไร</h3>
<p>เหตุผลที่สต็อกเพิ่มหรือลดโดยไม่มีเอกสารซื้อขาย เช่น ของเสียหาย หมดอายุ หาย หรือพบเพิ่มตอนตรวจนับ แต่ละรหัสผูกกับ <b>บัญชี</b> ที่ระบบลงมูลค่าส่วนต่างให้เอง</p>
<p>ใช้เลือกในหน้า <b>ตรวจนับสต็อก</b> (ตอนสร้างใบตรวจนับ) และหน้า <b>รับเข้า / เบิกออก</b> (รวมแท็บ ปรับราคา) — ไม่เลือกเหตุผล ระบบลงบัญชี <b>ปรับปรุงสินค้า</b> ในตั้งค่าบัญชี</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td><b>ผังบัญชี</b> (บัญชีที่ผูกกับแต่ละรหัส)</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td><b>ตรวจนับสต็อก</b> และ <b>รับเข้า / เบิกออก</b> (รวมปรับราคา)</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>รหัสเหตุผล (Reason Code) บอกสาเหตุและบัญชีของการปรับสต็อกที่ไม่มีเอกสารซื้อขาย ตรวจสอบย้อนหลังได้</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี เอง — ของเพิ่ม Dr สินค้า / Cr บัญชีของรหัส ของลด Dr บัญชีของรหัส / Cr สินค้า</td></tr>
</table>

<h3>ช่องต่าง ๆ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">รหัสเหตุผล</td><td>รหัสสั้น ตัวพิมพ์ใหญ่ เช่น <code>DMG</code>, <code>EXP</code>, <code>FOUND</code></td></tr>
    <tr><td class="text-nowrap">เหตุผล</td><td>คำอธิบาย เช่น "สินค้าเสียหาย"</td></tr>
    <tr><td class="text-nowrap">ใช้กับ</td><td><b>รับเข้า</b> (ของเพิ่ม) หรือ <b>จ่ายออก</b> (ของลด)</td></tr>
    <tr><td class="text-nowrap">บัญชี</td><td>บัญชีคู่กับบัญชีสินค้า เช่น ของเสียหาย → ค่าใช้จ่ายเบ็ดเตล็ด <code>59901</code>, พบเพิ่ม → รายได้อื่น <code>40901</code></td></tr>
    <tr><td class="text-nowrap">ศูนย์ต้นทุน</td><td>ไม่บังคับ แผนกที่รับผิดชอบ</td></tr>
    <tr><td class="text-nowrap">ใช้งาน</td><td>ปิดเมื่อเลิกใช้ รหัสจะไม่ขึ้นให้เลือกอีก</td></tr>
</table>

<h3>รหัสที่มากับการติดตั้ง</h3>
<ul>
    <li><code>OPEN</code> ยอดยกมา (รับเข้า → กำไรสะสม <code>30301</code>) — ใช้ตอนตั้งยอดสต็อกเริ่มต้นผ่าน <b>ตรวจนับสต็อก</b></li>
    <li><code>FOUND</code> พบสินค้าเพิ่ม · <code>USE</code> เบิกใช้ภายใน · <code>DMG</code> เสียหาย · <code>EXP</code> หมดอายุ · <code>LOST</code> สูญหาย</li>
</ul>
<p class="text-secondary">เปลี่ยนบัญชีให้ตรงผังบัญชีของบริษัทได้ มีผลกับรายการใหม่เท่านั้น รายการที่ลงบัญชีไปแล้วไม่เปลี่ยน</p>
