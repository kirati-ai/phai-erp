<h3>หน้านี้ใช้ทำอะไร</h3>
<p>สรุปสต็อกทั้งบริษัท: มูลค่า ของที่ต่ำกว่าสต็อกสำรอง ล็อตใกล้หมดอายุ ใบตรวจนับค้าง และความเคลื่อนไหวล่าสุด</p>

<h3>คลังสินค้าในระบบ ERP</h3>
<p>โมดูลคลังคือ <b>Inventory Management</b> — ศูนย์กลางที่ซื้อ ผลิต และขาย ส่งของเข้าออก ทุกการเปลี่ยนสต็อกบันทึกประวัติหนึ่งแถว คิด <b>ต้นทุนถัวเฉลี่ย</b> ตอนรับเข้า และลงบัญชีสินค้าให้เอง (สมุดรายวันประเภท IC)</p>

<h3>รายการเข้าออก</h3>
<ol>
    <li><b>รับเข้า</b>: รับสินค้าจากใบสั่งซื้อ (RCT-PO) · รับผลผลิตจากใบสั่งผลิต (RCT-WO) · รับเข้าเอง (RCT-UNP)</li>
    <li><b>ย้าย / แปลง</b>: โอนย้ายระหว่างคลัง-ตำแหน่ง (ISS-TR / RCT-TR ไม่ลงบัญชี) · แปลงวัตถุดิบเป็น FG (Dr สินค้า FG / Cr วัตถุดิบ)</li>
    <li><b>ออก</b>: ส่งของตามใบสั่งขาย (ISS-SO, Dr ต้นทุนขาย / Cr สินค้า) · เบิกเข้าใบสั่งผลิต (ISS-WO) · เบิกออกเอง (ISS-UNP)</li>
    <li><b>ตรวจนับ</b>: ใบตรวจนับ (CYC-CNT) ปรับยอดให้ตรงของจริง ผลต่างลงบัญชีของรหัสเหตุผล</li>
    <li><b>รายงาน</b>: ยอดคงเหลือ + ประวัติความเคลื่อนไหว = ข้อมูลของ <b>รายงานสินค้าและวัตถุดิบ</b> ม.87(3)</li>
</ol>

<h3>ส่งต่อโมดูลอื่น</h3>
<ul>
    <li><b>จัดซื้อ / ผลิต</b>: สินค้าต่ำกว่าสต็อกสำรองเป็นสัญญาณให้ขอซื้อหรือสั่งผลิต — MRP คำนวณให้</li>
    <li><b>ขาย</b>: ส่งของได้เท่าที่มีในคลัง (เว้นแต่ตั้งค่ายอมให้ติดลบ) วัตถุดิบ (RM) ขายตรงไม่ได้</li>
    <li><b>บัญชี</b>: มูลค่าสต็อกควรตรงกับบัญชีสินค้าใน <b>งบทดลอง</b></li>
</ul>

