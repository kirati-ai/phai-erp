<h3>หน้านี้คืออะไร</h3>
<p>รหัส <b>ภาษีมูลค่าเพิ่ม (VAT)</b> ที่เลือกในเอกสารซื้อขาย เช่น VAT 7%, VAT 0% หรือไม่มี VAT — ตั้งเป็นค่าเริ่มต้นที่ลูกค้าและผู้ขาย แล้วเอกสารใหม่จะดึงมาให้</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>อัตราภาษีมูลค่าเพิ่มตามประมวลรัษฎากร (7%, 0%, ยกเว้น)</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>ค่าเริ่มต้นของ <b>ลูกค้า</b> และ <b>ผู้ขาย</b> → เอกสารซื้อขาย → รายงานภาษีซื้อ / ขาย</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>รหัสภาษีมูลค่าเพิ่ม (VAT) — ข้อมูลหลัก</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — เอกสารลงภาษีซื้อ / ภาษีขาย ตามอัตรานี้</td></tr>
</table>

<h3>ช่องต่าง ๆ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">รหัสภาษี</td><td>เช่น <code>VAT7</code> (7%), <code>VAT0</code> (ส่งออก อัตรา 0%), <code>NON</code> (ไม่มี VAT เช่น ผู้ขายที่ไม่ได้จด VAT)</td></tr>
    <tr><td class="text-nowrap">ชื่อ</td><td>ชื่อที่อ่านเข้าใจ เช่น "VAT 7%"</td></tr>
    <tr><td class="text-nowrap">อัตรา (%)</td><td>ตัวเลขเปอร์เซ็นต์ เช่น <code>7</code> — ระบบคิดภาษีจากยอดก่อนภาษี</td></tr>
    <tr><td class="text-nowrap">ใช้งาน</td><td>ปิดเมื่อเลิกใช้ — จะไม่ขึ้นให้เลือกในเอกสารใหม่</td></tr>
</table>
<p>บัญชีที่ภาษีซื้อและภาษีขายลง ตั้งที่ <b>บัญชี › ตั้งค่าบัญชี</b></p>

<h3>ถ้าอัตรา VAT เปลี่ยน</h3>
<ol>
    <li>กด <b>เพิ่ม</b> รหัสใหม่ เช่น <code>VAT10</code> อัตรา 10</li>
    <li>เปลี่ยนรหัสภาษีที่ลูกค้าและผู้ขาย</li>
    <li>ปิด "ใช้งาน" ของรหัสเดิม — ไม่ควรแก้อัตราของรหัสเดิม เพื่อให้เอกสารเก่ายังอ่านถูก</li>
</ol>
<p class="text-secondary">รหัสภาษีที่ลูกค้า ผู้ขาย หรือสายผลิตภัณฑ์ใช้อยู่ ลบไม่ได้ — ภาษีหัก ณ ที่จ่ายอยู่คนละหน้า (<b>บัญชี › รหัสภาษีหัก ณ ที่จ่าย</b>)</p>
