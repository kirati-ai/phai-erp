<h3>หน้านี้คืออะไร</h3>
<p><b>กลุ่มสินค้า</b> ใช้จัดหมวดสินค้าไว้ดูและค้นหา เช่น เฟอร์นิเจอร์ไม้ เฟอร์นิเจอร์เหล็ก อะไหล่ — เลือกในช่อง <b>กลุ่มสินค้า</b> ของหน้า <b>สินค้าและวัตถุดิบ</b></p>
<p>ต่างจาก <b>สายผลิตภัณฑ์</b> ตรงที่กลุ่มสินค้าไม่มีผลกับการลงบัญชี ใช้แบ่งย่อยเพื่อความสะดวกเท่านั้น (จัดเป็นชั้น: สายผลิตภัณฑ์ → กลุ่มสินค้า → ประเภทสินค้า)</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>กำหนดเองตามการจัดหมวดของบริษัท</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>ช่อง <b>กลุ่มสินค้า</b> ในหน้า <b>สินค้าและวัตถุดิบ</b> ใช้ค้นหาและจัดกลุ่ม</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>กลุ่มสินค้า (Item Group) ข้อมูลหลักสำหรับจัดหมวด ไม่ใช่เอกสาร</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — บัญชีขึ้นกับสายผลิตภัณฑ์เท่านั้น</td></tr>
</table>

<h3>ช่องต่าง ๆ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">รหัสกลุ่ม</td><td>ตัวย่อ เช่น <code>WOOD</code>, <code>STEEL</code>, <code>SPARE</code></td></tr>
    <tr><td class="text-nowrap">ชื่อกลุ่มสินค้า</td><td>เช่น "เฟอร์นิเจอร์ไม้"</td></tr>
    <tr><td class="text-nowrap">ใช้งาน</td><td>ปิดเมื่อเลิกใช้ — จะไม่ขึ้นให้เลือกในสินค้า</td></tr>
</table>
<p class="text-secondary">กลุ่มที่สินค้าใช้อยู่ลบไม่ได้ ให้ปิด "ใช้งาน" แทน — ไม่จำเป็นต้องกำหนด ถ้าไม่ต้องการแบ่งกลุ่ม</p>
