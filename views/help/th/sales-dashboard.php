<h3>สายเอกสาร</h3>
<ol>
    <li><b>ใบเสนอราคา</b> (Quotation) — ได้งาน W / ไม่ได้งาน L ไม่ลงบัญชี</li>
    <li><b>ใบสั่งขาย</b> (Sales Order) — ยืนยันคำสั่งซื้อ ตรวจวงเงินเครดิต ไม่ลงบัญชี</li>
    <li><b>ใบส่งของ</b> (Delivery Order) — สต็อกลด Dr ต้นทุนขาย / Cr สินค้า</li>
