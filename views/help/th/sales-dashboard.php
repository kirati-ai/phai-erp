    <li><b>ใบวางบิล</b> (Billing Note) — ธรรมเนียมการค้า ไม่ใช่เอกสารภาษี ไม่ลงบัญชี</li>
    <li>ส่งต่อบัญชี: <b>รับชำระเงิน</b> (ใบเสร็จรับเงิน ม.105) Dr ธนาคาร / Dr ภาษีถูกหัก ณ ที่จ่าย / Cr ลูกหนี้ → <b>รายงานภาษีขาย</b></li>
</ol>
