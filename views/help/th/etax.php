<h3>หน้านี้คืออะไร</h3>
<p>ประวัติการส่ง <b>e-Tax Invoice by Email</b> ทุกครั้ง ทั้งที่ส่งสำเร็จและไม่สำเร็จ — ส่งจากปุ่ม <b>ส่ง e-Tax</b> ในหน้าใบแจ้งหนี้/ใบลดหนี้ แต่ละครั้งส่งถึงผู้ซื้อ 1 คน พร้อมสำเนาถึงระบบ สพธอ. ซึ่งประทับเวลาแล้วส่งต่อให้ผู้ซื้อ</p>
<p><b>เอกสารรอส่ง e-Tax</b> (เฉพาะเมื่อเปิดใช้ e-Tax) เหนือรายการแสดงใบกำกับภาษี ใบลดหนี้ ใบเพิ่มหนี้ ที่ไม่ได้ยกเลิกและยังไม่เคยส่งสำเร็จ นับตั้งแต่เดือนที่เริ่มใช้ e-Tax กด <b>ส่ง e-Tax</b> เพื่อเปิดเอกสารแล้วส่งจากหน้านั้น</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td><b>ใบแจ้งหนี้ / ใบกำกับภาษี</b> และ <b>ใบแจ้งหนี้ / ใบลดหนี้</b> (ปุ่ม ส่ง e-Tax)</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>ผู้ซื้อ + สำเนาถึง สพธอ. ซึ่งประทับเวลาแล้วส่งข้อมูลให้กรมสรรพากร</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>ใบกำกับภาษีอิเล็กทรอนิกส์ (e-Tax Invoice by Email) ตาม ม.86/4 และประกาศอธิบดีกรมสรรพากรเรื่อง e-Tax</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — ใบกำกับภาษีลงบัญชีไปแล้วตอนออก</td></tr>
</table>

