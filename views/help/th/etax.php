<p>คลิกแถวเพื่อเปิดเอกสารนั้น ถ้าไม่สำเร็จ แก้สาเหตุ (ดู <b>ตั้งค่า e-Tax / อีเมล</b>) แล้วกด <b>ส่ง e-Tax</b> ในเอกสารอีกครั้ง</p>

<h3>ส่งเมื่อไร</h3>
<ul>
    <li>ใบแจ้งหนี้ ใบลดหนี้ ใบเพิ่มหนี้ ส่งหลังบันทึก — ใส่อีเมลผู้ซื้อ (ค่าเริ่มต้นจากข้อมูลลูกค้า) ระบบสร้าง PDF/A-3 ให้เอง</li>
    <li>ใบแจ้งหนี้ที่ยกเลิกแล้ว กด <b>ส่ง e-Tax</b> อีกครั้งเพื่อแจ้งยกเลิก (CIV)</li>
</ul>

<h3>XML ประจำเดือน (แบบ XML)</h3>
<p>ถ้าอัปโหลดใบรับรองไว้ที่ <b>ตั้งค่า e-Tax / อีเมล</b> จะมีช่องเดือนและปุ่ม <b>XML ประจำเดือน</b> ด้านบน: ได้ไฟล์ zip ของ XML ที่ลงลายมือชื่อแล้วของทุกใบกำกับภาษี ใบลดหนี้ ใบเพิ่มหนี้ และใบรับในเดือนนั้น (เอกสารที่สร้างไม่ได้อยู่ใน <code>errors.txt</code>) นำไป "Upload XML" ที่ <code>etax.rd.go.th</code> ภายในวันที่ 15 ของเดือนถัดไป</p>
<p class="text-secondary">ใช้แบบอีเมลหรือแบบ XML อย่างใดอย่างหนึ่ง ไม่ใช้คู่กัน — เอกสารที่ยกเลิกแล้วไม่มี XML ให้ออกใบลดหนี้แทน</p>
