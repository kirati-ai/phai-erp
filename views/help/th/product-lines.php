    <tr><td class="text-nowrap">มาจาก</td><td><b>ผังบัญชี</b> (บัญชีสินค้า ต้นทุนขาย ขาย ซื้อ) และ <b>หมวดสินทรัพย์ถาวร</b> สำหรับประเภท FA</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>ทุกสินค้าใน <b>สินค้าและวัตถุดิบ</b> — เอกสารซื้อ คลัง ผลิต ขาย หาบัญชีจากสายของสินค้า</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>สายผลิตภัณฑ์ (Product Line) ตัวเชื่อมสินค้ากับบัญชีแยกประเภท แบ่ง FG สินค้าสำเร็จรูป / RM วัตถุดิบ / FA สินทรัพย์ถาวร</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี เอง — กำหนดว่าเอกสารอื่นลงบัญชีใด</td></tr>
</table>

<h3>ช่องต่าง ๆ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">รหัส</td><td>เช่น <code>FG</code>, <code>RM</code>, <code>FG-FURNITURE</code>, <code>RM-STEEL</code></td></tr>
    <tr><td class="text-nowrap">ประเภทสต็อก</td><td>
        <b>สินค้าสำเร็จรูป (FG)</b> = ของที่ขาย ·
        <b>วัตถุดิบ (RM)</b> = ของที่ซื้อมาใช้ผลิต (ขายตรงไม่ได้ ต้องแปลงเป็น FG ก่อน) ·
        <b>สินทรัพย์ถาวร (FA)</b> = เครื่องจักร อุปกรณ์ ที่ซื้อมาใช้งาน</td></tr>
    <tr><td class="text-nowrap">หมวดสินทรัพย์ถาวร</td><td>ต้องเลือกเมื่อประเภทเป็น FA เท่านั้น — ของที่รับเข้าจะลงบัญชีสินทรัพย์ของหมวดนั้น</td></tr>
    <tr><td class="text-nowrap">แท็บ บัญชี</td><td>บัญชีสินค้าคงคลัง รายได้จากการขาย ต้นทุนขาย การซื้อ งานระหว่างทำ ของสินค้าในสายนี้ — ช่องที่เว้นว่าง ระบบใช้บัญชีตั้งต้นใน <b>บัญชี › ตั้งค่าบัญชี</b></td></tr>
    <tr><td class="text-nowrap">ใช้งาน</td><td>ปิดเมื่อเลิกใช้ — สินค้าใหม่จะเลือกสายนี้ไม่ได้</td></tr>
</table>

<h3>เพิ่มสายผลิตภัณฑ์</h3>
<ol>
    <li>ถ้าต้องการแยกบัญชี ไปที่ <b>บัญชี › ผังบัญชี</b> เพิ่มรหัสบัญชีก่อน</li>
    <li>กด <b>เพิ่ม</b> ใส่รหัส ชื่อ และเลือก <b>ประเภทสต็อก</b></li>
    <li>เปิดแท็บ <b>บัญชี</b> เลือกบัญชีที่ต้องการ แล้วกด <b>บันทึก</b></li>
    <li>ไปที่ <b>สินค้าและวัตถุดิบ</b> เลือกสายนี้ในช่อง <b>สายผลิตภัณฑ์</b> ของสินค้า</li>
</ol>
