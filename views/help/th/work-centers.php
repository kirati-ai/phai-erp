<h3>อัตราเหล่านี้ใช้ที่ไหน</h3>
<ul>
    <li><b>สูตรการผลิต</b> แท็บขั้นตอน: ต้นทุน/หน่วย = เวลาต่อชิ้น × (ค่าแรง + ค่าเครื่องจักร + ค่าโสหุ้ย)</li>
    <li><b>ใบสั่งผลิต</b> แท็บแรงงาน: ค่าแรงจริง = ชั่วโมง × ค่าแรง/ชม. ของพนักงาน ถ้าพนักงานไม่ได้ตั้งค่าแรงไว้ ใช้ <b>ค่าแรง/ชม.</b> ของศูนย์งาน และค่าโสหุ้ยจริง = ชั่วโมง × (ค่าเครื่องจักร/ชม. + ค่าโสหุ้ย/ชม.) ของศูนย์งาน เข้างานระหว่างทำด้วย</li>
</ul>

