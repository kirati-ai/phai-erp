<h3>ทำใบวางบิล</h3>
<ol>
    <li>ติ๊กใบใน <b>ใบแจ้งหนี้รอวางบิล</b> เหนือรายการ (ลูกค้ารายเดียวกัน แถวสีแดง = เลยครบกำหนด) แล้วกด <b>ทำใบวางบิล</b> — หรือกด <b>เพิ่ม</b> เลือก <b>ลูกค้า</b> ตารางแสดงใบแจ้งหนี้ค้างชำระที่ยังไม่อยู่ในใบวางบิลอื่น</li>
    <li>ใส่ <b>วันที่</b> และ <b>นัดชำระ</b> (วันที่ลูกค้านัดจ่าย) หมายเหตุถ้ามี</li>
    <li>ติ๊กใบแจ้งหนี้ที่จะวางบิล (ช่องบนหัวตารางติ๊กทั้งหมด) แล้วกด <b>บันทึก</b></li>
    <li>กด <b>พิมพ์</b> ได้ใบวางบิล A4 มีจำนวนเงินตัวอักษร และช่องเซ็น ผู้รับสินค้า / ผู้รับเอกสาร และผู้วางบิล</li>
</ol>

<h3>ข้อควรรู้</h3>
<ul>
    <li>ยอดในใบวางบิล = ยอดค้างของแต่ละใบ ณ วันที่ทำ (หักส่วนที่ชำระบางส่วนแล้ว)</li>
    <li>ใบวางบิลหนึ่งใบต้องเป็นสกุลเงินเดียวกัน</li>
    <li>ใบแจ้งหนี้หนึ่งใบอยู่ในใบวางบิลที่รอชำระได้ใบเดียว และยกเลิกใบแจ้งหนี้นั้นไม่ได้ระหว่างนั้น</li>
    <li>รับเงินที่หน้า <b>รับชำระเงิน</b> (บัญชี → ลูกหนี้) ไม่ใช่ที่หน้านี้</li>
</ul>

<h3>สถานะ</h3>
<ul>
    <li><b>รอชำระ</b> — ยกเลิกได้ด้วยปุ่ม <b>ยกเลิกเอกสาร</b> (เช่น จะวางบิลใหม่) ใบแจ้งหนี้กลับไปเลือกได้อีก</li>
    <li><b>ชำระแล้ว</b> — เปลี่ยนเองเมื่อทุกใบแจ้งหนี้ในใบวางบิลชำระครบ</li>
    <li><b>ยกเลิก</b></li>
</ul>
