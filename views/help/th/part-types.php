<h3>หน้านี้คืออะไร</h3>
<p><b>ประเภทสินค้า</b> ใช้แบ่งสินค้าละเอียดลงอีกชั้นจาก <b>กลุ่มสินค้า</b> เช่น โต๊ะ เก้าอี้ ชั้นวาง — เลือกในช่อง <b>ประเภทสินค้า</b> ของหน้า <b>สินค้าและวัตถุดิบ</b> ไม่มีผลกับการลงบัญชี</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>กำหนดเอง เป็นชั้นย่อยถัดจาก <b>กลุ่มสินค้า</b></td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>ช่อง <b>ประเภทสินค้า</b> ในหน้า <b>สินค้าและวัตถุดิบ</b></td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>ประเภทสินค้า (Item Type) ข้อมูลหลักสำหรับจัดหมวด ไม่ใช่เอกสาร</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี — บัญชีขึ้นกับสายผลิตภัณฑ์เท่านั้น</td></tr>
</table>

<h3>ช่องต่าง ๆ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">รหัสประเภท</td><td>ตัวย่อ เช่น <code>TABLE</code>, <code>CHAIR</code>, <code>SHELF</code></td></tr>
    <tr><td class="text-nowrap">ชื่อประเภท</td><td>เช่น "โต๊ะ"</td></tr>
    <tr><td class="text-nowrap">ใช้งาน</td><td>ปิดเมื่อเลิกใช้ — จะไม่ขึ้นให้เลือกในสินค้า</td></tr>
</table>
