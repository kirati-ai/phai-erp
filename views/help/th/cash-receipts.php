<h3>หน้านี้คืออะไร</h3>
<p>บันทึก <b>เงินที่รับจากลูกค้า</b> ตัดกับใบแจ้งหนี้ที่ค้างชำระ รับหลายใบในครั้งเดียวได้ บันทึกภาษีที่ลูกค้าหัก ณ ที่จ่ายไว้ได้ และพิมพ์ <b>ใบเสร็จรับเงิน</b> ยอดเป็นเงินบาท</p>
<p><b>ใบแจ้งหนี้รอรับชำระ</b> เหนือรายการแสดงใบแจ้งหนี้และใบเพิ่มหนี้ที่ยังรับเงินไม่ครบ เรียงตามวันครบกำหนด (ตัวแดง = เกินกำหนด, ซ่อนเมื่อไม่มี) กด <b>รับชำระ</b> ระบบเปิดใบรับชำระใหม่พร้อมลูกค้าและยอดเต็มของใบนั้น</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td><b>ใบแจ้งหนี้ / ใบกำกับภาษี</b>, ใบเพิ่มหนี้ หรือ <b>ใบวางบิล</b> ที่ค้างรับ</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td><b>ลูกหนี้คงค้าง</b> ลดลง · <b>กระทบยอดธนาคาร</b> · e-Tax ใบรับ (XML)</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>ใบเสร็จรับเงิน (Receipt, CR) ตาม ม.105 ทวิ — ภาษีที่ลูกค้าหักไว้มี 50 ทวิ จากลูกค้าเป็นหลักฐาน</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>Dr ธนาคาร + ภาษีถูกหัก ณ ที่จ่าย / Cr ลูกหนี้การค้า</td></tr>
</table>

<h3>ขั้นตอน</h3>
<ol>
    <li>กด <b>เพิ่ม</b> (หรือ <b>รับชำระใหม่</b> จากหน้าลูกหนี้คงค้าง) เลือกลูกค้า ระบบแสดงใบแจ้งหนี้ที่ค้าง เรียงตามวันครบกำหนด</li>
    <li>เลือกวันที่ และ <b>บัญชีรับ/จ่ายเงิน</b> ที่เงินเข้า (เงินสดหรือบัญชีธนาคาร)</li>
    <li>ใส่ยอด <b>รับเงิน</b> ของแต่ละใบ ปุ่มลูกศรข้างเลขที่ใส่ <b>เต็มยอด</b> ให้ — รับบางส่วนได้</li>
    <li>ถ้าลูกค้าหักภาษี ใส่ยอดในช่อง <b>ถูกหัก ณ ที่จ่าย</b> ของใบนั้น (รับเงิน + ถูกหัก ณ ที่จ่าย = ยอดที่ตัดหนี้ ไม่เกินยอดคงเหลือ)</li>
    <li>ตรวจยอดรวมให้ตรงกับเงินเข้าจริง แล้ว <b>บันทึก</b> จากนั้น <b>พิมพ์ / PDF</b> ใบเสร็จ</li>
</ol>
<p class="text-secondary">ตัวอย่าง: ใบแจ้งหนี้ 10,700 (ค่าบริการก่อน VAT 10,000) ลูกค้าหัก 3% = 300 ใส่ รับเงิน 10,400 และ ถูกหัก ณ ที่จ่าย 300 — ขอหนังสือรับรอง 50 ทวิ จากลูกค้าเก็บไว้</p>

<h3>หักใบลดหนี้</h3>
<p>ใบลดหนี้ที่ยังไม่ได้ใช้แสดงในรายการเป็น <b>ยอดคงเหลือติดลบ</b> ใส่ยอดติดลบ (หรือกดเต็มยอด) เพื่อหักกับใบแจ้งหนี้ในใบรับเงินเดียวกัน — ยอดรับสุทธิต้องไม่ติดลบ และใบลดหนี้ไม่มีการหัก ณ ที่จ่าย</p>

<h3>ลงบัญชีอย่างไร</h3>
<p>เดบิต บัญชีธนาคารที่เลือก (รับเงิน) และ <b>ภาษีถูกหัก ณ ที่จ่าย</b> / เครดิต ลูกหนี้ของลูกค้า — ใบแจ้งหนี้ที่รับครบเป็น <b>ชำระแล้ว</b> และใบวางบิลที่มีใบนั้นอัปเดตตาม</p>
<p>รับชำระใบแจ้งหนี้ <b>งานบริการ</b> (ภาษีขายถึงกำหนดเมื่อรับชำระ, ม.78/1): ภาษีตามสัดส่วนที่รับถึงกำหนดตอนนี้ — เดบิต <b>ภาษีขายยังไม่ถึงกำหนด</b> / เครดิต <b>ภาษีขาย</b> (รับงวดสุดท้ายได้ส่วนที่เหลือทั้งหมด) ใบนี้พิมพ์เป็น <b>ใบเสร็จรับเงิน / ใบกำกับภาษี</b> มีมูลค่าบริการและภาษี และอยู่ในรายงานภาษีขายของเดือนที่รับเงิน</p>

<h3>e-Tax แบบ XML</h3>
<p>ถ้าอัปโหลดใบรับรองไว้ที่ <b>ตั้งค่า e-Tax / อีเมล</b> จะมีปุ่ม <b>XML e-Tax</b> ได้ใบรับ (T01) ที่ลงลายมือชื่อแล้ว แต่ละบรรทัดคือใบแจ้งหนี้ที่รับชำระ</p>

<h3>การยกเลิก</h3>
<p><b>ยกเลิกเอกสาร</b> แล้วใบแจ้งหนี้กลับเป็นค้างชำระ และกลับรายการบัญชีด้วยวันที่วันนี้ — สถานะ <b>ลงบัญชีแล้ว</b> → <b>ยกเลิก</b> วันที่รับเงินต้องไม่ก่อนงวดบัญชีที่เปิด</p>

<p class="text-secondary">จ่าย/รับเป็น<b>เงินสด</b>: เลือกบัญชี <b>CASH เงินสดย่อย (ของผู้ทำรายการ)</b> — เงินออกจาก/เข้ากล่องเงินสดย่อยของคนที่ทำเอกสารนี้ (ดูหน้า เงินสดย่อย) ยกเลิกเอกสารได้เมื่อเดือนนั้นของกล่องยังไม่นับ</p>

<h3>เอกสารแนบ</h3>
<p>หัวข้อ <b>เอกสารแนบ</b> ใต้เอกสารที่บันทึกแล้ว: กด <b>แนบไฟล์</b> แนบรูปหรือ PDF ได้หลายไฟล์ เช่น สลิปโอนของลูกค้า หนังสือรับรองหัก ณ ที่จ่าย (50 ทวิ) ที่ลูกค้าหักเรา — คลิกเพื่อเปิด กด × เพื่อลบ — กดรูปคลิปท้ายแถวในหน้ารายการ เปิดหน้าต่างเอกสารแนบของแถวนั้นได้เลยโดยไม่ต้องเปิดเอกสาร (คลิปสีเขียวพร้อมตัวเลข = จำนวนไฟล์ที่แนบไว้)</p>
<p class="text-secondary">แนบต้องมีสิทธิ์เพิ่มหรือแก้ไขของหน้านี้ ลบต้องมีสิทธิ์แก้ไขหรือลบ แนบได้ทุกสถานะ</p>
