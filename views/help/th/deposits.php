<h3>หน้านี้ใช้ทำอะไร</h3>
<p>บันทึก <b>เงินมัดจำ</b> ที่ลูกค้าจ่ายตามใบสั่งขายก่อนส่งสินค้า ได้ <b>ใบรับเงินมัดจำ / ใบกำกับภาษี</b> เพราะรับเงินก่อนส่งมอบถือเป็นจุดความรับผิดภาษี (ม.78) แล้วใบกำกับภาษีตอนส่งของจะหักมัดจำนี้ออกให้เอง</p>

<h3>อยู่ตรงไหนของระบบ</h3>
