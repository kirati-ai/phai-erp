<h3>ใช้งาน</h3>
<ol>
    <li>เปิดใบสั่งขาย กด <b>รับเงินมัดจำ</b> (หรือเลือกจากรายการใบสั่งขายที่เปิดอยู่ในหน้าใหม่ ค้นด้วยเลขที่ ลูกค้า หรือเลข PO ลูกค้า) ระบบแสดงยอดใบสั่งขายและมัดจำที่รับไปแล้ว</li>
    <li>เลือกบัญชีธนาคาร ใส่ <b>รับเงิน (รวม VAT)</b> ระบบแยกเป็นมูลค่าก่อนภาษีกับภาษีตามอัตราของใบสั่งขาย รวมมัดจำต้องไม่เกินยอดใบสั่งขาย</li>
    <li>บันทึกแล้วกด <b>พิมพ์ / PDF</b> ให้ลูกค้า</li>
    <li>เมื่อส่งของและออกใบกำกับภาษี มัดจำถูกหักให้เอง (เก่าก่อน) สถานะ <b>ยังหักไม่หมด</b> → <b>หักครบแล้ว</b> — ยกเลิกใบกำกับภาษี มัดจำกลับมาให้หักใหม่</li>
    <li><b>ยกเลิกเอกสาร</b> ได้เฉพาะมัดจำที่ยังไม่ถูกหัก ระบบกลับรายการบัญชีด้วยวันที่วันนี้</li>
</ol>
<p class="text-secondary">ใบกำกับภาษีที่หักมัดจำยังสร้าง XML e-Tax ไม่ได้ ใช้ PDF แทน</p>

<p class="text-secondary">จ่าย/รับเป็น<b>เงินสด</b>: เลือกบัญชี <b>CASH เงินสดย่อย (ของผู้ทำรายการ)</b> — เงินออกจาก/เข้ากล่องเงินสดย่อยของคนที่ทำเอกสารนี้ (ดูหน้า เงินสดย่อย) ยกเลิกเอกสารได้เมื่อเดือนนั้นของกล่องยังไม่นับ</p>
