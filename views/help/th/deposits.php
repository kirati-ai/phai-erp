    <tr><td class="text-nowrap">มาจาก</td><td><b>ใบสั่งขาย</b> ที่ยังเปิดอยู่และเป็นเงินบาท — กดปุ่ม <b>รับเงินมัดจำ</b> บนใบสั่งขาย</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td><b>ใบส่งของ → ใบแจ้งหนี้ / ใบกำกับภาษี</b> ของใบสั่งขายเดียวกัน: หักมัดจำ (ก่อน VAT) ออกจากมูลค่าสินค้า คิดภาษีเฉพาะส่วนที่เหลือ หักหลายใบได้จนครบ — เข้า <b>รายงานภาษีขาย</b> และ <b>ภ.พ.30</b> ของเดือนที่รับเงิน</td></tr>
