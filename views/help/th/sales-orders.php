<h3>หน้านี้ใช้ทำอะไร</h3>
<p>บันทึกคำสั่งซื้อของลูกค้า แล้วส่งของตามใบนี้ ไม่มีขั้นอนุมัติ (พิมพ์ไปเซ็น) ยอดค้างส่งใช้ในการวางแผนผลิต (MRP)</p>

