<h3>สร้างใบสั่งขาย</h3>
<ol>
    <li>จาก <b>ใบเสนอราคา</b> กด <b>สร้างใบสั่งขาย</b> หรือกดที่แถวใน <b>ใบเสนอราคารอตอบรับ</b> เหนือรายการ (ขึ้นเฉพาะเมื่อมีใบที่ยังไม่หมดอายุ) หรือกด <b>เพิ่ม</b> ที่หน้านี้</li>
    <li>เลือก <b>ลูกค้า</b> และ <b>ส่งจากคลัง</b> ใส่ <b>เลขที่ PO ลูกค้า</b> ถ้ามี</li>
    <li>ใส่บรรทัด สินค้า จำนวน ราคา (เติมจาก <b>ราคาขาย</b>) และ <b>ต้องการวันที่</b> ของแต่ละบรรทัดได้</li>
    <li>กด <b>บันทึก</b> แล้วกด <b>ส่งของ</b> เมื่อพร้อม</li>
</ol>

