<h3>ใบสั่งขายแบบกำหนดส่ง</h3>
<p>ลูกค้าที่สั่งระยะยาวแล้วให้ส่งเป็นงวด (เช่น เดือนละ 10 ชุด) เลือก <b>ประเภทใบสั่ง = แบบกำหนดส่ง</b> แล้วกด <b>ตารางกำหนดส่ง</b> กรอกงวดตามตารางที่ลูกค้าส่งมา — ลูกค้ารายใหญ่มักส่งตารางมาทาง <b>EDI</b> (ส่งข้อมูลจากระบบถึงระบบ) ส่งของครบงวดที่มีแล้วใบสั่งยังเปิดอยู่จนกด <b>ปิด</b></p>

<h3>รับเงินมัดจำ</h3>
<p>ใบสั่งขายที่ยังเปิดอยู่ (เงินบาท) มีปุ่ม <b>รับเงินมัดจำ</b> ออก <b>ใบรับเงินมัดจำ / ใบกำกับภาษี</b> ให้ลูกค้า แล้วใบกำกับภาษีตอนส่งของของใบสั่งขายนี้หักมัดจำออกให้เอง</p>

<h3>วงเงินเครดิต</h3>
<p>ถ้าเปิดตรวจวงเงินใน <b>ตั้งค่าการขาย</b> และยอดของลูกค้าเกิน <b>วงเงินเครดิต</b> ระบบบันทึกให้แต่ขึ้นคำเตือน "เกินวงเงินเครดิต" — ตัดสินใจเองว่าจะส่งของหรือรอชำระก่อน</p>

<h3>สถานะ</h3>
<ul>
    <li><b>รอส่งของ</b> — แก้ไขได้จนกว่าจะส่งของครั้งแรก ส่งบางส่วนได้หลายครั้ง</li>
    <li><b>ปิดแล้ว</b> — ส่งครบทุกบรรทัด (ปิดเอง) หรือกด <b>ปิดใบสั่งขาย</b> เมื่อส่วนที่เหลือจะไม่ส่งแล้ว</li>
    <li><b>ยกเลิก</b> — กด <b>ยกเลิกเอกสาร</b> ได้เฉพาะยังไม่ได้ส่งของเลย ถ้ามาจากใบเสนอราคา ใบเสนอราคากลับเป็น รอตอบรับ</li>
</ul>
<p class="text-secondary">ส่งของไปแล้วแก้หรือยกเลิกใบสั่งขายไม่ได้ ถ้าลูกค้าลดจำนวน ให้กด ปิดใบสั่งขาย</p>

