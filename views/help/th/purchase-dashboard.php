<h3>หน้านี้ใช้ทำอะไร</h3>
<p>สรุปงานจัดซื้อในหน้าเดียว: ยอดสั่งซื้อ ใบสั่งซื้อที่รอผู้ขายส่งของ และผู้ขายหลัก คลิกการ์ดหรือแถวเพื่อเปิดเอกสาร</p>

<h3>จัดซื้อในระบบ ERP</h3>
<p>โมดูลจัดซื้อคือ <b>Procurement</b> และเป็นส่วนของ <b>SRM</b> (Supplier Relationship Management การบริหารผู้ขาย) — เลือกผู้ขาย สั่งของ ติดตามการส่งมอบ ตรวจรับ จนส่งต่อให้บัญชีจ่ายเงิน</p>

<h3>สายเอกสาร</h3>
<ol>
    <li><b>ใบขอซื้อ</b> (Purchase Requisition, PR) — คำขอภายใน หรือสร้างจาก MRP ไม่ลงบัญชี</li>
    <li><b>ใบสั่งซื้อ</b> (Purchase Order, PO) — ส่งผู้ขาย พิมพ์ไปเซ็น ไม่ลงบัญชี</li>
    <li><b>รับสินค้าเข้าคลัง</b> (Goods Receipt) — ตามใบส่งของ / ใบกำกับภาษีของผู้ขาย สต็อกเพิ่ม Dr สินค้า / Cr สินค้ารับแล้วรอใบแจ้งหนี้ (GRNI)</li>
    <li><b>ค่าใช้จ่ายนำเข้า</b> (Landed Cost) — ค่าขนส่ง อากร เพิ่มเข้าต้นทุนสินค้า (ถ้ามี)</li>
    <li>ส่งต่อบัญชี: <b>ตั้งหนี้เจ้าหนี้</b> → <b>ใบสำคัญจ่าย</b> → <b>จ่ายชำระเจ้าหนี้</b> + หนังสือรับรองหัก ณ ที่จ่าย (50 ทวิ) → <b>รายงานภาษีซื้อ</b></li>
</ol>

<h3>ส่งต่อโมดูลอื่น</h3>
<ul>
    <li><b>คลังสินค้า</b>: ของที่รับเข้าไปอยู่ในยอดคงเหลือ ต้นทุน = ราคาหลังส่วนลด × อัตราแลกเปลี่ยน</li>
    <li><b>ผลิต</b>: MRP สร้างใบขอซื้อวัตถุดิบ และนับใบขอซื้อ / ใบสั่งซื้อค้างรับเป็นของที่จะมา</li>
    <li><b>บัญชี</b>: เจ้าหนี้ (AP) ภาษีซื้อ และภาษีหัก ณ ที่จ่าย</li>
</ul>

