<h3>หน้านี้ใช้ทำอะไร</h3>
<p>บวก <b>ค่าขนส่ง อากรขาเข้า ค่าประกันภัย</b> และค่าใช้จ่ายอื่นที่เกิดกับการซื้อครั้งหนึ่ง เข้าไปในต้นทุนสินค้าของ <b>ใบรับสินค้า</b> นั้น เพื่อให้ต้นทุนต่อหน่วยตรงกับที่จ่ายจริง</p>
<p>รายการคือใบรับสินค้า<b>นำเข้า</b> (ใบสั่งซื้อสกุลเงินต่างประเทศ — ซื้อเป็นเงินบาทไม่มีค่าใช้จ่ายนำเข้า) พร้อม สกุลเงิน มูลค่า (บาท) ของสินค้า และยอดค่าใช้จ่ายนำเข้าที่ใส่ไว้ คลิกแถวเพื่อเปิดใบรับนั้น</p>

