<h3>ใส่ค่าใช้จ่ายแล้วปันส่วน</h3>
<ol>
    <li>คลิกใบรับในรายการ กด <b>แก้ไข</b> — ใบรับจากใบสั่งซื้อสกุลเงินต่างประเทศที่ยังไม่ได้ปันส่วน ขึ้นในกล่อง <b>ใบรับสินค้านำเข้ารอใส่ค่าใช้จ่าย</b> เหนือรายการ กด <b>ใส่ค่าใช้จ่าย</b> เปิดได้เลย</li>
    <li>ใส่บิลละบรรทัด: ชนิด เลขที่เอกสาร ผู้เรียกเก็บ จำนวนเงิน แล้วกด <b>บันทึก</b> — ป้ายเป็น <b>รอปันส่วน</b> ยังแก้ได้</li>
    <li>ตรวจยอดแล้วกด <b>ปันส่วนเข้าต้นทุน</b> และยืนยัน</li>
</ol>

<h3>ปันส่วนแล้วเกิดอะไร</h3>
<ul>
    <li>ต้นทุนถัวเฉลี่ยของสินค้าเพิ่มขึ้น โดยกระจายไปบนจำนวนที่ยังเหลือในคลังขณะนั้น</li>
    <li>ถ้าสินค้าขายหรือเบิกไปหมดแล้ว ค่าใช้จ่ายส่วนนั้นลงต้นทุนขาย สินค้าที่ไม่เก็บสต็อกลงเป็นค่าใช้จ่าย</li>
    <li>ลงบัญชีให้เอง ลงวันที่วันนี้: เดบิต สินค้าคงคลัง / เครดิต <b>สินค้ารับแล้วรอใบแจ้งหนี้ (GRNI)</b> — ยังไม่เป็นหนี้จนกว่าผู้เรียกเก็บส่งใบแจ้งหนี้มา</li>
    <li>ค่าใช้จ่ายที่มีผู้เรียกเก็บ ขึ้นใน <b>รับสินค้ารอตั้งหนี้</b> ของหน้า <b>ตั้งหนี้</b> บรรทัดละรายการ พร้อมป้ายชนิด (เช่น ค่าขนส่ง) และเลขที่เอกสาร เมื่อใบแจ้งหนี้มาถึง ติ๊กทุกบรรทัดที่อยู่ในบิลนั้น ตั้งหนี้จากรายการนั้น: เดบิต GRNI + ภาษีซื้อ / เครดิต เจ้าหนี้ — GRNI ของค่าใช้จ่ายนี้จึงเป็นศูนย์ ไม่ลงต้นทุนซ้ำ</li>
    <li>ค่าใช้จ่ายที่ปันส่วนแล้วขึ้นป้าย <b>ปันส่วนแล้ว</b> <b>แก้และยกเลิกไม่ได้</b> — บิลที่มาทีหลัง เพิ่มบรรทัดใหม่แล้วปันส่วนอีกครั้งได้ จนกว่าจะตั้งหนี้</li>
    <li>เมื่อตั้งหนี้บรรทัดใดแล้ว ป้ายเป็น <b>ตั้งหนี้แล้ว</b> ไม่มีปุ่มแก้ไข — ค่าใช้จ่ายของใบรับนี้ปิดแล้ว (ยกเลิกใบตั้งหนี้ก่อน จึงแก้ได้อีก)</li>
</ul>
