<p>ตำแหน่งที่ระบบเลือกให้ก่อนเวลารับของ เบิกวัตถุดิบเข้าการผลิต และโอนย้าย มาจาก <b>ตำแหน่งรับของเริ่มต้น</b> ของแต่ละคลัง ตั้งที่ <b>ตั้งค่าระบบ › สาขา (Site)</b></p>
<p class="text-secondary">ต้นทุนสินค้าเป็นแบบถัวเฉลี่ย คำนวณใหม่ทุกครั้งที่รับเข้า ไม่มีตัวเลือกในหน้านี้ — รูปแบบเลขที่เอกสารคลัง (IC รับ/เบิก, TO โอนย้าย, PI ตรวจนับ) ตั้งที่ <b>ตั้งค่าระบบ › ตั้งค่าเลขที่เอกสาร</b></p>

<h3>เลขที่เอกสาร</h3>
<p>ตารางท้ายหน้ากำหนดคำนำหน้า รูปแบบ และเลขถัดไปของเอกสารในหมวดนี้ (ใบรับ/เบิกสินค้า ใบโอนสินค้า ใบตรวจนับ) แล้วกด <b>บันทึก</b> ของตาราง — มีผลกับเอกสารใหม่เท่านั้น ดูรายละเอียดรูปแบบใน ตั้งค่าระบบ → <b>ตั้งค่าเลขที่เอกสาร</b> ซึ่งรวมทุกหมวดไว้ที่เดียว</p>
