<h3>สถานะ</h3>
<ul>
    <li><b>ค้างชำระ</b> — รอรับเงิน ใส่ใน <b>ใบวางบิล</b> ได้</li>
    <li><b>ชำระแล้ว</b> — รับเงินครบที่หน้า <b>รับชำระเงิน</b> (บัญชี → ลูกหนี้)</li>
    <li><b>ยกเลิก</b> — กด <b>ยกเลิกเอกสาร</b> ได้เฉพาะยังไม่มีการชำระ และไม่อยู่ในใบวางบิลที่ยังรอชำระ (ยกเลิกใบวางบิลก่อน) ระบบกลับรายการบัญชีลงวันนี้ และใบส่งของกลับมารอออกใบแจ้งหนี้</li>
    <li><b>ลบ</b> — ใบที่ยกเลิกแล้ว ลบได้เมื่อเป็นเลขที่ล่าสุดของชุด ยังไม่ส่ง e-Tax ไม่มีใบวางบิล/ใบเสร็จ/ใบลดหนี้อ้างถึง และอยู่ในงวดที่ยังเปิด — ลบรายการบัญชีทิ้งและคืนเลขที่ให้ใบถัดไป (ยกเลิกผิดใบทันทีหลังออก) นอกนั้นต้องเก็บไว้เป็นใบยกเลิก เพราะใบกำกับภาษีที่ออกแล้วต้องเก็บพร้อมเลขที่</li>
</ul>

