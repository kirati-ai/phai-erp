<h3>ออกใบแจ้งหนี้</h3>
<ol>
    <li>กด <b>ยืนยันส่งของ</b> ที่ใบส่งของ แล้วระบบเปิดใบแจ้งหนี้ที่เติมจากใบส่งของนั้นให้เลย</li>
    <li>หรือกด <b>ออกใบแจ้งหนี้</b> ที่แถวใน <b>ใบส่งของรอออกใบแจ้งหนี้</b> เหนือรายการ หรือกด <b>เพิ่ม</b> แล้วเลือกใบส่งของ</li>
    <li>หน้าใบแจ้งหนี้ใหม่ เติมสินค้า จำนวน (ตามที่ส่ง แก้ไม่ได้) และราคาตามใบสั่งขายไว้ — แก้ <b>วันที่</b> <b>ครบกำหนด</b> <b>เลขที่ PO ลูกค้า</b> <b>หมายเหตุ</b> <b>ราคา</b> และ <b>ส่วนลด</b> ได้ แล้วกด <b>บันทึก</b></li>
    <li>เปิดใบแล้วกด <b>พิมพ์</b> ได้ใบแจ้งหนี้ / ใบกำกับภาษี A4</li>
