<h3>ส่งของ</h3>
<ol>
    <li>กด <b>ส่งของ</b> ที่แถวใน <b>ใบสั่งขายรอส่งของ</b> เหนือรายการ (หนึ่งแถวต่อบรรทัดสินค้า: ส่งที่ (อำเภอ จังหวัดของลูกค้า) ค้างส่ง มีอยู่ในคลัง และ <b>พอส่ง</b> / <b>ขาด</b> / <b>ไม่มีของ</b> — ของในคลังให้บรรทัดที่ต้องการก่อนก่อน; ถ้าขาด ช่อง <b>ของที่จะเข้า</b> บอกใบสั่งผลิตหรือใบสั่งซื้อที่ค้างอยู่ และ <b>ส่งได้</b> = วันกำหนดเสร็จ/รับของของใบสุดท้ายที่ต้องรอ ขึ้น "ยังไม่มีแผน" ให้รัน MRP; แถวสีแดง = เลยวันที่ลูกค้าต้องการ) หรือที่ใบสั่งขาย หรือ <b>เพิ่ม</b> ที่หน้านี้แล้วเลือก <b>ใบสั่งขาย</b></li>
    <li>เปิดมาแล้ว <b>ส่งครั้งนี้</b> เติมให้เท่าที่ค้างส่งและมีของ (ของพอก็ส่งครบในใบเดียว) แก้จำนวนได้ — บรรทัดที่เว้นว่างไม่ส่ง</li>
    <li>ระบบเลือก <b>ตำแหน่ง</b> และ <b>ล็อต</b> ให้เอง เรียงตำแหน่งและวันหมดอายุเก่าก่อน ล็อตเดียวไม่พอก็เพิ่มแถวล็อตถัดไปของบรรทัดเดียวกันจนครบ (ปุ่ม × ลบแถวที่เพิ่ม) เปลี่ยนตำแหน่ง/ล็อตเองได้ (คอลัมน์ <b>มีอยู่</b> บอกจำนวนที่ตำแหน่ง/ล็อตนั้นมีก่อนส่ง เป็นสีแดงเมื่อไม่พอส่งที่ค้าง — ใส่จำนวนเกินคงเหลือ ช่องจะแดงพร้อม "คงเหลือไม่พอ" ใต้ช่อง)</li>
    <li>ใส่ <b>การจัดส่ง</b> และ <b>เลขติดตามพัสดุ</b> ถ้ามี เช่น "รถบริษัท" หรือ <code>TH0123456789</code></li>
    <li>กด <b>ยืนยันส่งของ</b> ระบบถามยืนยันอีกครั้ง (ตัดสต็อกแล้วแก้ไม่ได้) บันทึกแล้วเปิดหน้า <b>ใบแจ้งหนี้</b> ที่เติมจากใบส่งของนี้ให้ตรวจ/แก้ (วันที่ ครบกำหนด เลขที่ PO ลูกค้า หมายเหตุ ราคา ส่วนลด) ก่อนกดบันทึก — ไม่บันทึกก็ออกทีหลังจากคิวรอออกใบแจ้งหนี้ได้</li>
</ol>

<h3>ข้อควรรู้</h3>
<ul>
    <li>ส่งเกินจำนวนค้างส่งไม่ได้ วันที่ส่งต้องไม่เกินวันนี้</li>
    <li>สินค้าคุมล็อตต้องเลือกล็อต รายการที่ไม่เก็บสต็อก (ค่าบริการ รายการพิมพ์เอง) ไม่ต้องเลือกตำแหน่ง</li>
    <li>ส่งครบทุกบรรทัดแล้ว ใบสั่งขายปิดเอง</li>
    <li>ใบส่งของหนึ่งใบ ออกใบแจ้งหนี้ได้หนึ่งใบ ราคาตามใบสั่งขาย</li>
</ul>

<h3>สถานะ</h3>
<ul>
    <li><b>รอออกใบแจ้งหนี้</b> — เปิดใบแล้วกด <b>ออกใบแจ้งหนี้</b> หรือทำที่หน้า <b>ใบแจ้งหนี้ / ใบกำกับภาษี</b></li>
    <li><b>ออกใบแจ้งหนี้แล้ว</b> — มีปุ่มไปยังใบแจ้งหนี้ ถ้ายกเลิกใบแจ้งหนี้ ใบส่งของกลับมารอออกใบแจ้งหนี้</li>
</ul>
