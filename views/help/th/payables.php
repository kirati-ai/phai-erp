<h3>รับสินค้ารอตั้งหนี้</h3>
<p>เหนือรายการแสดงใบรับสินค้าที่ยังไม่ตั้งหนี้ และ <b>ค่าใช้จ่ายนำเข้า</b> (ค่าขนส่ง ชิปปิ้ง อากร ประกันภัย) ที่ปันส่วนแล้วแต่ผู้เรียกเก็บยังไม่ได้ตั้งหนี้ บรรทัดละรายการ — มีป้ายชนิดและเลขที่เอกสาร (เช่น เลข AWB) กำกับ (ซ่อนเมื่อไม่มี) ติ๊กใบรับของผู้ขายเดียวกันที่อยู่ในใบแจ้งหนี้ฉบับเดียวกัน แล้วกด <b>ตั้งหนี้</b> ระบบเปิดหน้าตั้งหนี้ใหม่พร้อมผู้ขายและใบรับที่ติ๊กไว้ — ยกเลิกการตั้งหนี้ภายหลัง ใบรับจะกลับมาอยู่ในรายการนี้</p>

<h3>ขั้นตอน</h3>
<ol>
    <li>เลือกผู้ขาย ระบบแสดงใบรับสินค้าที่ยังไม่ตั้งหนี้ ติ๊กใบที่อยู่ในใบแจ้งหนี้นี้ </li>
    <li>ค่าใช้จ่ายที่ไม่มีใบรับ กด <b>เพิ่มบรรทัด</b> เลือกบัญชี ศูนย์ต้นทุน (ถ้ามี) คำอธิบาย และจำนวนเงิน</li>
    <li>ตรวจยอดก่อนภาษี ภาษี และยอดรวมให้ตรงใบแจ้งหนี้ แล้ว <b>บันทึก</b></li>
</ol>

<h3>ลงบัญชีอย่างไร</h3>
<ul>
    <li>ตั้งหนี้: เดบิต สินค้ารับแล้วรอใบแจ้งหนี้ (ตามยอดที่ใบรับลงไว้) หรือค่าใช้จ่าย, เดบิต ภาษีซื้อ / เครดิต บัญชีเจ้าหนี้ — ผลต่างเศษสตางค์ระหว่างใบรับกับยอดตั้งหนี้ลงบัญชี ปรับปรุงสินค้า</li>
    <li>ใบลดหนี้: เลือก <b>อ้างถึงการตั้งหนี้</b> เดิมของผู้ขายเดียวกัน ใส่เฉพาะบรรทัดค่าใช้จ่าย ลงบัญชีกลับข้าง (เดบิตเจ้าหนี้ / เครดิตค่าใช้จ่ายและภาษีซื้อ) ยอดติดลบ นำไปหักในใบสำคัญจ่ายได้</li>
</ul>
<p>ปุ่ม <b>รายการบัญชี</b> เปิดรายการที่ลงไว้ ปุ่ม <b>พิมพ์ / PDF</b> พิมพ์ใบตั้งหนี้</p>

<h3>สถานะและการยกเลิก</h3>
<p><b>ค้างจ่าย</b> → <b>ชำระแล้ว</b> เมื่อนำเข้า <b>ใบสำคัญจ่าย</b> (หนี้ย้ายไปอยู่ที่ใบสำคัญจ่าย) — <b>ยกเลิกเอกสาร</b> ได้เฉพาะที่ยังค้างจ่าย ระบบกลับรายการบัญชีด้วยวันที่วันนี้ และใบรับกลับไปรอตั้งหนี้ ถ้าอยู่ในใบสำคัญจ่ายแล้ว ต้องยกเลิกใบสำคัญจ่ายก่อน</p>

<h3>หัก ณ ที่จ่ายตามบรรทัด</h3>
<p>ทุกบรรทัด (ใบรับสินค้าและค่าใช้จ่ายอื่น) มีช่อง <b>หัก ณ ที่จ่าย</b> เลือกรหัสของบรรทัดนั้น เช่น ค่าขนส่ง 1% ค่าบริการ 3% — ผู้ขายที่ตั้ง <b>หัก ณ ที่จ่าย</b> ไว้ในหน้าผู้ขาย (แท็บการค้า) จะเติมให้เอง ตอนจ่ายชำระ ตารางหัก ณ ที่จ่ายรวมยอดก่อน VAT ตามรหัสให้เอง (จ่ายบางส่วน = ตามสัดส่วน)</p>

<h3>แก้ไขตั้งหนี้ที่ค้างจ่าย</h3>
<p>ปุ่ม <b>แก้ไข</b> ขึ้นเมื่อตั้งหนี้ยัง <b>ค้างจ่าย</b> และยังไม่อยู่ในใบสำคัญจ่าย: แก้เลขที่ใบแจ้งหนี้ วันที่ ครบกำหนด หมายเหตุ บัญชีเจ้าหนี้ เพิ่ม/แก้/ลบบรรทัดค่าใช้จ่าย และเปลี่ยนรหัสหัก ณ ที่จ่ายของทุกบรรทัด — บรรทัดจากใบรับสินค้าแก้จำนวนเงินไม่ได้ (ต้องตรงกับที่รับเข้าคลัง) ระบบลงบัญชีเฉพาะส่วนต่างเป็นรายการแก้ไขในวันที่ของตั้งหนี้ (ถ้างวดนั้นปิดแล้วใช้วันนี้) ไม่ลบรายการเดิม</p>

<h3>เอกสารแนบ</h3>
<p>หัวข้อ <b>เอกสารแนบ</b> ใต้เอกสารที่บันทึกแล้ว: กด <b>แนบไฟล์</b> แนบรูปหรือ PDF ได้หลายไฟล์ เช่น ใบกำกับภาษี / ใบแจ้งหนี้ของผู้ขาย (หลักฐานภาษีซื้อ) — คลิกเพื่อเปิด กด × เพื่อลบ — กดรูปคลิปท้ายแถวในหน้ารายการ เปิดหน้าต่างเอกสารแนบของแถวนั้นได้เลยโดยไม่ต้องเปิดเอกสาร (คลิปสีเขียวพร้อมตัวเลข = จำนวนไฟล์ที่แนบไว้)</p>
