<h3>หน้านี้คืออะไร</h3>
<p><b>ทะเบียนสินทรัพย์ถาวร</b> ของบริษัท (เครื่องจักร รถ คอมพิวเตอร์ อาคาร) ตั้งแต่ขึ้นทะเบียน ลงค่าเสื่อมรายเดือน โอนสถานที่ จนขายหรือตัดจำหน่าย สถานะ: <b>ร่าง</b> → <b>ใช้งาน</b> → <b>จำหน่ายแล้ว</b></p>
<p>เหนือรายการมีงานรอ (ซ่อนเมื่อไม่มี, เฉพาะผู้มีสิทธิ์แก้ไข): <b>สินทรัพย์รอขึ้นทะเบียน</b> คือสถานะร่าง กด <b>ขึ้นทะเบียน</b> เพื่อเปิดสินทรัพย์นั้น และ <b>ค่าเสื่อมรอลงบัญชี</b> คือเดือนถึงเดือนก่อนที่ยังไม่ลงค่าเสื่อม (ตัวแดง = ค้างเกินหนึ่งเดือน) กด <b>ลงค่าเสื่อม</b> เพื่อเปิดหน้าค่าเสื่อมรายเดือนของเดือนนั้น</p>

