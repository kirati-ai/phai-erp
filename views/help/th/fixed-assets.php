<h3>เอกสารแนบ</h3>
<p>หัวข้อ <b>เอกสารแนบ</b> ใต้ข้อมูลสินทรัพย์: กด <b>แนบไฟล์</b> แนบรูปหรือ PDF ได้หลายไฟล์ เช่น ใบกำกับภาษี ใบรับประกัน รูปสินทรัพย์ โฉนด คู่มือ — คลิกเพื่อเปิด กด × เพื่อลบ — กดรูปคลิปท้ายแถวในหน้ารายการ เปิดหน้าต่างเอกสารแนบของแถวนั้นได้เลยโดยไม่ต้องเปิดเอกสาร (คลิปสีเขียวพร้อมตัวเลข = จำนวนไฟล์ที่แนบไว้) แนบต้องมีสิทธิ์เพิ่มหรือแก้ไข ลบต้องมีสิทธิ์แก้ไขหรือลบ แนบได้ทุกสถานะ ลบร่างสินทรัพย์แล้วไฟล์แนบถูกลบด้วย</p>

<h3>ค่าเสื่อมรายเดือน</h3>
<p>ปุ่ม <b>ค่าเสื่อมรายเดือน</b> ในหน้ารายการ: ใส่เดือน กด <b>คำนวณ / ตรวจสอบ</b> ดูผลตรวจสอบของแต่ละสินทรัพย์ ติ๊กแล้วกด <b>ลงบัญชีรายการที่เลือก</b> (หรือ <b>ลงบัญชีค่าเสื่อม</b> ทีละสินทรัพย์ในหน้าสินทรัพย์) — เดบิต ค่าเสื่อมราคา / เครดิต ค่าเสื่อมสะสม ลงวันสิ้นเดือน</p>
<p>ต้องลงต่อเนื่องทีละเดือน เป็นเดือนที่สิ้นสุดแล้ว และอยู่ในงวดที่เปิด เดือนเดิมลงซ้ำไม่ได้ เดือนสุดท้ายปรับให้เหลือมูลค่าซากพอดี</p>

<h3>โอน ขาย กลับรายการ</h3>
<ul>
    <li><b>โอนสถานที่ / ผู้รับผิดชอบ</b> — เปลี่ยนสาขา ศูนย์ต้นทุน สถานที่ ผู้ดูแล ไม่ลงบัญชี</li>
    <li><b>ขาย / ตัดจำหน่าย</b> — ลงค่าเสื่อมให้ครบถึงเดือนก่อนจำหน่ายก่อน (เดือนที่จำหน่ายไม่มีค่าเสื่อม) ใส่ราคาขายสุทธิและ <b>บัญชีรับเงิน / พักจำหน่าย</b>: ระบบล้างทุนและค่าเสื่อมสะสม ผลต่างลงบัญชีกำไร/ขาดทุนจำหน่าย — ภาษีขายและการรับเงินบันทึกในเอกสารบัญชีแยก โดยใช้บัญชีพักเพื่อไม่ลงซ้ำ</li>
    <li><b>กลับรายการล่าสุด</b> — แก้รายการล่าสุดที่ผิด ใส่วันที่ (ในงวดที่เปิด ไม่ก่อนรายการเดิม) และเหตุผล ประวัติเดิมยังอยู่</li>
</ul>
