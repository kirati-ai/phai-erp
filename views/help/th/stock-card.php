<h3>หน้านี้ใช้ทำอะไร</h3>
<p><b>บัญชีคุมสินค้า (Stock card)</b> ในช่วงวันที่ แยกทีละสินค้า: ยอดยกมา ทุกรายการรับ/จ่าย พร้อมจำนวน ต้นทุนต่อหน่วย มูลค่า และยอดคงเหลือสะสม — ยอดคงเหลือบรรทัดสุดท้ายของแต่ละสินค้าตรงกับ <b>ยอดคงเหลือสินค้า</b> ณ วันนั้นเสมอ</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>ทุกเอกสารที่เปลี่ยนสต็อก: รับสินค้า ส่งของ เบิก/รับจากการผลิต รับเข้า/เบิกออกเอง โอนย้าย ตรวจนับ ปรับราคา (อ่านจาก <b>ประวัติความเคลื่อนไหว</b>)</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>เก็บไว้ให้เจ้าพนักงานตรวจ และใช้กระทบยอดสินค้าคงเหลือกับบัญชีสินค้าในงบการเงิน</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td><b>รายงานสินค้าและวัตถุดิบ</b> ที่ผู้ประกอบการจดทะเบียน VAT ต้องจัดทำ (ประมวลรัษฎากร ม.87(3)) แยกสินค้าทีละรายการ แสดงรับ จ่าย คงเหลือ</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี (รายงาน) — แต่ละรายการลงบัญชีไปแล้วตอนทำเอกสารต้นทาง</td></tr>
</table>

<h3>ใช้งาน</h3>
<ol>
    <li>เปิดหน้ามาเห็น <b>ทุกสินค้า</b> ที่มียอดยกมาหรือมีความเคลื่อนไหวในเดือนนี้ เรียงตามรหัส — ดูสินค้าเดียวเลือกในช่องสินค้า (เลือก ทุกสินค้า หรือกด Delete เพื่อกลับ) กรอง <b>ประเภท</b> FG/RM (ตามสายผลิตภัณฑ์) และคลัง (เว้นว่าง = ทุกคลัง) ได้</li>
    <li>เลือก <b>เดือน</b> ด้วย ‹ เดือน › (ได้วันที่ 1 ถึงสิ้นเดือน) หรือกรอกช่วงวันที่เอง (ป้ายเดือนจะเป็น กำหนดช่วงเอง)</li>
    <li>แต่ละสินค้าเริ่มด้วยแถวชื่อสินค้า แล้ว <b>ยอดยกมา</b> ก่อนวันเริ่ม ทุกความเคลื่อนไหวเรียงตามวันที่ และแถวรวมรับ จ่าย ยอดยกไป — ท้ายสุดคือ <b>รวมทุกสินค้า</b> (เฉพาะมูลค่า เพราะหน่วยนับต่างกัน) ใช้เทียบกับบัญชีสินค้าคงเหลือ</li>
    <li>กด <b>พิมพ์ / PDF</b> ได้แบบแนวนอน A4 ตามตัวกรองที่เลือก</li>
</ol>
<p class="text-secondary">ดูทุกคลังพร้อมกัน การโอนย้ายจะขึ้นทั้งโอนออกและโอนเข้า ยอดรวมไม่เปลี่ยน — มูลค่าคิดจากต้นทุนต่อหน่วย ณ เวลาที่เคลื่อนไหว (ต้นทุนถัวเฉลี่ย) การปรับราคาขึ้นเป็นจ่ายออกราคาเดิม + รับเข้าราคาใหม่</p>
