<h3>หน้านี้คืออะไร</h3>
<p>ส่งเอกสารจากข้างนอก (PDF หรือรูป) ให้คนในองค์กร <b>เซ็นตามลำดับ</b> เช่น ผู้ช่วยผู้จัดการ → ผู้จัดการ → เจ้าของ ทุกช่องลงนามบอกเวลา <b>รับ เปิด เซ็น</b> เซ็นครบแล้วทุกคนได้ <b>ฉบับสุดท้าย</b> ฉบับเดียวกัน พร้อมเอกสารแนบท้ายและหน้าหลักฐานการลงนาม</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>เมนู <b>เอกสารลงนาม → ซองเอกสาร</b> กด <b>สร้างซองใหม่</b> (ต้องมีสิทธิ์เพิ่มของหน้าซองเอกสาร) — คนที่ถูกขอให้เซ็นเห็นที่แท็บ <b>รอฉันเซ็น</b> และปุ่มซองจดหมายแถบบน</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>เซ็นครบ ได้ PDF ฉบับสุดท้าย ส่งให้ทุกคนในซองทางอีเมล (ถ้าตั้งค่าอีเมลไว้) และอยู่ที่แท็บ <b>เอกสารของฉัน</b> ตลอดไป ตรวจไฟล์ที่หน้า <b>ตรวจเอกสาร</b></td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>เอกสารที่ลงลายมือชื่ออิเล็กทรอนิกส์ พร้อมหลักฐานการลงนาม</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี</td></tr>
</table>

<h3>สร้างและส่งซอง</h3>
<ol>
    <li><b>เอกสารหลัก</b>: ไฟล์ที่มีช่องให้เซ็น (PDF หรือรูป ไฟล์ Word ให้บันทึกเป็น PDF ก่อน) <b>แนบท้าย</b>: ไฟล์ประกอบ ไม่มีช่องเซ็น — ระบบทำไฟล์ให้สะอาดก่อนเก็บ (ตัด JavaScript ลิงก์ ฟอร์ม และสิ่งที่ซ่อนอยู่) PDF ที่ตั้งรหัสผ่านอัปโหลดไม่ได้</li>
    <li><b>ผู้ลงนาม</b>: เพิ่มทีละคน เลือกผู้ใช้ ใส่ตำแหน่ง เลือกบทบาท ลงนาม / อนุมัติ / รับทราบ (ได้แค่ฉบับสุดท้าย) ปุ่มลูกศรเลื่อนขั้น คนในขั้นเดียวกันเซ็นพร้อมกันได้ ขั้นถัดไปเริ่มเมื่อขั้นก่อนเซ็นครบ</li>
    <li><b>วางช่อง</b>: เลือกผู้ลงนาม (จุดสี) เลือกชนิดช่องทางขวา แล้วคลิกที่หน้าเอกสาร ผู้ลงนามทุกคนต้องมีช่องลายเซ็นหรือชื่อย่ออย่างน้อยหนึ่งช่อง</li>
    <li>ดูรายการ <b>ตรวจก่อนส่ง</b> แล้วกด <b>ส่ง</b> — หลังส่งแก้เอกสารไม่ได้ ต้องถอนแล้วสร้างซองใหม่</li>
</ol>

<h3>เครื่องมือในตัวแก้เอกสาร</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">เลือก</td><td>คลิกช่อง Shift + คลิกเพื่อเลือกหลายช่อง หรือลากกรอบรอบช่อง</td></tr>
    <tr><td class="text-nowrap">ย้าย / ขนาด</td><td>ลากช่อง ลากมุมขวาล่าง ปุ่มลูกศรเลื่อนทีละ 1 pt (Shift = 10 pt) หรือพิมพ์ตำแหน่งเป็นมิลลิเมตร</td></tr>
    <tr><td class="text-nowrap">หลายหน้า</td><td><b>คัดลอกไป</b> ทุกหน้า / ทุกหน้ายกเว้นหน้าแรก / หน้าคี่-คู่ / หน้าที่เลือก (เช่น 2-5, 8) ติ๊ก <b>เชื่อมกัน</b> ให้แก้ที่เดียวทุกหน้าเปลี่ยนตาม และ <b>ลบช่องนี้จาก</b> หลายหน้าในครั้งเดียว</td></tr>
    <tr><td class="text-nowrap">จัดตำแหน่ง</td><td>เลือกหลายช่องแล้วจัดชิดซ้าย กึ่งกลาง ขวา บน ล่าง กระจายระยะ หรือทำขนาดเท่ากัน</td></tr>
    <tr><td class="text-nowrap">คีย์ลัด</td><td>Ctrl+C / Ctrl+V คัดลอก วาง, Ctrl+D ทำซ้ำ, Ctrl+Z / Ctrl+Y ย้อน ทำซ้ำ, Delete ลบ, Esc ยกเลิก</td></tr>
    <tr><td class="text-nowrap">ผู้ส่งใส่เอง</td><td><b>กล่องข้อความ</b> (ขนาด ตัวหนา เอียง ขีดเส้นใต้ สี จัดแนว) และ <b>ตราคำ</b> เช่น อนุมัติ ด่วน สำเนาถูกต้อง</td></tr>
</table>

<h3>เซ็น</h3>
<ul>
    <li>เปิดจากแท็บ <b>รอฉันเซ็น</b> ครั้งแรกที่เปิดคือเวลา "เปิด" กรอกช่องสีของคุณ ลายเซ็นใช้ <b>ลายเซ็นของฉัน</b> ที่ตั้งไว้ หรือวาดใหม่ แล้วกด <b>เซ็นและส่ง</b> (หรือ <b>อนุมัติและส่ง</b>)</li>
    <li><b>ไม่อนุมัติ</b> ต้องบอกเหตุผล ซองจะหยุด ผู้ส่งและคนที่เซ็นแล้วได้แจ้ง</li>
    <li>ผู้ส่งกด <b>ส่งเตือน</b>, <b>ถอนซอง</b> หรือ <b>เปลี่ยนผู้ลงนาม</b> ที่ยังไม่เซ็นได้จากหน้าซอง</li>
</ul>

<h3>ฉบับสุดท้ายและการตรวจ</h3>
<ul>
    <li>ทุกหน้ามีท้ายกระดาษ: เลขซอง หน้า x / รวม ไฟล์ไหนหน้าไหน รหัสเนื้อหา และ QR ไปหน้าตรวจ เนื้อหาเดิมถูกย่อเล็กน้อยเพื่อไม่ให้ท้ายกระดาษทับ</li>
    <li>หน้าหลักฐานการลงนามบอกจำนวนหน้าของทุกไฟล์ ลายนิ้วมือ (SHA-256) ทั้งไฟล์และรายหน้า ผู้ลงนามพร้อมเวลารับ เปิด เซ็น IP และประวัติทั้งหมดที่เก็บเป็นโซ่ hash</li>
    <li>หน้า <b>ตรวจเอกสาร</b>: เลือกไฟล์ ระบบบอกว่าตรงกับที่เซ็นไว้ หรือหน้าไหนต่าง ไฟล์ไม่ถูกเก็บ</li>
    <li>เวลาทั้งหมดเป็นนาฬิกาของเครื่องแม่ข่าย ให้เครื่องตั้งเวลาจากอินเทอร์เน็ต</li>
    <li><b>คนนอกองค์กร</b> (ปุ่ม "คนนอก" ในตัวแก้) เซ็นผ่านบริการ Phai Sign (phai.monrak.net): เขาได้อีเมลพร้อมลิงก์ ยืนยันรหัส 6 หลักที่ส่งไปอีเมลเดียวกัน อ่านเอกสาร พิมพ์ชื่อแล้วเลือกแบบตัวอักษรลายมือ และติ๊กยินยอม ผลกลับมาที่ซองเอง และบริการลบสำเนาทิ้ง เมื่อซองเสร็จเขาได้ลิงก์ดาวน์โหลดฉบับสุดท้าย</li>
    <li>ผู้ดูแลระบบต้องเปิดบริการก่อน: หน้าซองเอกสาร ปุ่ม <b>บริการคนนอก</b> ลงทะเบียนเครื่อง แล้วเปิดใช้ (เอกสารของคนนอกจะไปพักที่บริการชั่วคราว แจ้งคนนอกตาม PDPA) เลือกได้ว่าจะบันทึก SHA-256 ของฉบับสุดท้ายที่บริการเป็นพยานจากภายนอกหรือไม่</li>
    <li>ลิงก์ของคนนอกหมดอายุหรือถูกล็อก กด <b>ส่งเตือน</b> แล้วเขาได้ลิงก์ใหม่ ลิงก์เก่าใช้ไม่ได้</li>
</ul>
