<h3>หน้านี้ใช้ทำอะไร</h3>
<p>สรุปการเงิน: ลูกหนี้และเจ้าหนี้คงค้าง ลูกหนี้ที่เลยกำหนด เจ้าหนี้ที่ใกล้ครบกำหนด ภาษีมูลค่าเพิ่มโดยประมาณ และบัญชีธนาคาร</p>

<h3>บัญชีในระบบ ERP</h3>
<p>โมดูลบัญชีคือ <b>Finance</b> — ปลายทางของทุกโมดูล เอกสารซื้อ คลัง ผลิต ขาย ลงสมุดรายวันให้เอง แบ่งเป็น <b>AP</b> เจ้าหนี้ <b>AR</b> ลูกหนี้ <b>GL</b> บัญชีแยกประเภท <b>FA</b> สินทรัพย์ถาวร และ <b>ภาษี</b> (VAT, หัก ณ ที่จ่าย, e-Tax)</p>

<h3>สายเอกสาร</h3>
<ol>
    <li><b>เจ้าหนี้ (AP)</b>: ตั้งหนี้ตามใบกำกับภาษีผู้ขาย (Dr GRNI หรือค่าใช้จ่าย / Dr ภาษีซื้อ / Cr เจ้าหนี้) → ใบสำคัญจ่าย (Payment Voucher) → จ่ายชำระ (Dr ใบสำคัญจ่ายค้าง / Cr ธนาคาร / Cr ภาษีหัก ณ ที่จ่ายค้าง) + หนังสือรับรองหัก ณ ที่จ่าย 50 ทวิ → รายงาน ภ.ง.ด.3 / 53</li>
    <li><b>ลูกหนี้ (AR)</b>: ใบแจ้งหนี้ / ใบกำกับภาษี ม.86/4 (จากงานขาย หรือทำเอง รวมใบลดหนี้ ม.86/10 ใบเพิ่มหนี้ ม.86/9) → รับชำระเงิน / ใบเสร็จรับเงิน ม.105 (Dr ธนาคาร / Dr ภาษีถูกหัก ณ ที่จ่าย / Cr ลูกหนี้)</li>
    <li><b>ภาษี</b>: รายงานภาษีซื้อ + รายงานภาษีขาย (ม.87) → ยื่น ภ.พ.30 · e-Tax Invoice by Email / XML</li>
    <li><b>เงินสดและธนาคาร</b>: เงินสดย่อย บัญชีธนาคาร กระทบยอดธนาคาร</li>
    <li><b>GL</b>: สมุดรายวันทั่วไป (JE) → งบทดลอง → ปิดงวด</li>
    <li><b>FA</b>: ทะเบียนสินทรัพย์ → ค่าเสื่อมราคารายเดือน (Dr ค่าเสื่อมราคา / Cr ค่าเสื่อมราคาสะสม)</li>
</ol>

<h3>รับจากโมดูลอื่น</h3>
<ul>
    <li><b>จัดซื้อ</b>: รับสินค้า Dr สินค้า / Cr GRNI · ค่าใช้จ่ายนำเข้า (LC)</li>
    <li><b>คลังสินค้า</b>: รับเข้า เบิกออก ตรวจนับ ปรับราคา (IC)</li>
    <li><b>ผลิต</b>: เบิก แรงงาน รับผลผลิต ผ่านงานระหว่างทำ (WO)</li>
    <li><b>ขาย</b>: ส่งของ (ต้นทุนขาย) และใบแจ้งหนี้ (AR)</li>
</ul>

