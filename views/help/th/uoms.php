<h3>หน้านี้คืออะไร</h3>
<p>รายการ <b>หน่วยนับ</b> ที่ใช้กับสินค้าและวัตถุดิบ เช่น ชิ้น กล่อง กิโลกรัม — เลือกในช่อง <b>หน่วยนับ</b> ของหน้า <b>สินค้าและวัตถุดิบ</b> และใช้เป็นหน่วยน้ำหนัก/หน่วยขนาดได้ด้วย</p>

<h3>อยู่ตรงไหนของระบบ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">มาจาก</td><td>ติดตั้งมาพร้อมหน่วยพื้นฐาน เพิ่มเองได้</td></tr>
    <tr><td class="text-nowrap">ไปต่อ</td><td>ช่อง <b>หน่วยนับ</b> ใน <b>สินค้าและวัตถุดิบ</b> แล้วแสดงในทุกเอกสารและสต็อก</td></tr>
    <tr><td class="text-nowrap">ชื่อเอกสาร</td><td>หน่วยนับ (Unit of Measure, UM) ข้อมูลอ้างอิงพื้นฐาน</td></tr>
    <tr><td class="text-nowrap">ลงบัญชี</td><td>ไม่ลงบัญชี</td></tr>
</table>

<h3>ช่องต่าง ๆ</h3>
<table class="table table-sm">
    <tr><td class="text-nowrap">รหัส</td><td>ตัวย่อสั้น ๆ พิมพ์เป็นตัวพิมพ์ใหญ่ เช่น <code>PC</code>, <code>BOX</code>, <code>KG</code></td></tr>
    <tr><td class="text-nowrap">ชื่อหน่วยนับ</td><td>ชื่อเต็มที่อ่านเข้าใจ เช่น "ชิ้น", "กล่อง 12 ชิ้น"</td></tr>
    <tr><td class="text-nowrap">ใช้งาน</td><td>ปิดเมื่อเลิกใช้ — หน่วยนี้จะไม่ขึ้นให้เลือกในสินค้าใหม่ แต่สินค้าเดิมยังใช้ได้</td></tr>
</table>

<h3>เพิ่มหน่วยนับ</h3>
<ol>
    <li>กด <b>เพิ่ม</b> ใส่รหัสและชื่อ</li>
    <li>กด <b>บันทึก</b> (หรือ Enter)</li>
</ol>
<p class="text-secondary">หน่วยนับที่สินค้าใช้อยู่ลบไม่ได้ ให้ปิด "ใช้งาน" แทน — ระบบไม่แปลงหน่วย ซื้อ ขาย และเก็บสต็อกเป็นหน่วยเดียวกับที่ตั้งในสินค้า</p>
