<h3>ขั้นตอน</h3>
<ol>
    <li>กด <b>เพิ่ม</b> เลือกผู้ขาย ระบบแสดง <b>ตั้งหนี้ที่ค้างจ่าย</b> ที่ยังไม่อยู่ในใบสำคัญจ่ายอื่น (รวมใบลดหนี้ซึ่งยอดติดลบ)</li>
    <li>ติ๊กใบที่จะจ่ายรอบนี้ ใส่ <b>วันนัดจ่าย</b> (ถ้ามี) และหมายเหตุ</li>
    <li><b>บันทึก</b> แล้วกด <b>พิมพ์</b> ไปเซ็นอนุมัติ</li>
    <li>เมื่อจะจ่าย กด <b>จ่ายชำระ</b> บนใบสำคัญจ่าย ระบบเปิดหน้าจ่ายชำระใหม่พร้อมผู้ขายและยอดของใบนี้</li>
</ol>

<h3>ลงบัญชีอย่างไร</h3>
<p>เดบิต บัญชีเจ้าหนี้ของแต่ละการตั้งหนี้ / เครดิต <b>เจ้าหนี้ตามใบสำคัญจ่าย</b> (ตั้งค่าบัญชี) — การตั้งหนี้ที่อยู่ในใบนี้เปลี่ยนเป็น <b>ชำระแล้ว</b> เพราะหนี้ย้ายมาอยู่ที่ใบสำคัญจ่าย</p>
<p>ยอดรวมต้องมากกว่าศูนย์ ถ้าใบลดหนี้มากกว่ายอดตั้งหนี้ ให้เลือกการตั้งหนี้เพิ่มให้พอหัก</p>

