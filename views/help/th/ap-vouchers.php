<h3>หน้านี้คืออะไร</h3>
<p><b>ใบสำคัญจ่าย (VO)</b> รวมการตั้งหนี้ที่ค้างจ่ายของ <b>ผู้ขายรายเดียว</b> หลายใบเข้าด้วยกัน พิมพ์ให้ผู้จัดทำ ผู้ตรวจสอบ ผู้อนุมัติ เซ็น ก่อนจ่ายเงินจริงในหน้า <b>จ่ายชำระเจ้าหนี้</b></p>
<p><b>ตั้งหนี้รอทำใบสำคัญจ่าย</b> เหนือรายการแสดงตั้งหนี้และใบลดหนี้ที่ยังไม่อยู่ในใบสำคัญจ่าย (ตัวแดง = เลยกำหนดชำระ, ซ่อนเมื่อไม่มี) ติ๊กของผู้ขายเดียวกันแล้วกด <b>ทำใบสำคัญจ่าย</b> ระบบเปิดใบใหม่พร้อมผู้ขายและรายการที่ติ๊กไว้</p>

